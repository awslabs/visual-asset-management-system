"""Trusted client-IP resolution for the API Gateway authorizer.

``identity.sourceIp`` is the client address API Gateway reports for the request, which a
client cannot choose. A single VAMS deployment can receive API requests three ways, and IP
allow-list checks must work for all of them without breaking any:

1. **Direct to API Gateway** — existing CLIs/integrations registered against the
   execute-api URL. ``sourceIp`` is the real client. No forwarding headers are present.
2. **Behind an ALB** — the ALB rule issues an HTTP redirect to the execute-api host, so
   the client then calls API Gateway directly. This is effectively the direct case:
   ``sourceIp`` is the real client.
3. **Behind CloudFront** — CloudFront is a reverse proxy in the request path. For a request
   through the deployment's distribution, API Gateway reports the viewer (the address that
   connected to CloudFront) as ``sourceIp``, and the CloudFront edge appears only as the
   trailing ``X-Forwarded-For`` hop: ``<entries the viewer sent>, <viewer>, <edge>``. The
   address API Gateway reports is the entry CloudFront appended, not an entry the viewer sent,
   so ``sourceIp`` is the real client here too. The trailing hop is the edge, not
   ``sourceIp``, so the header step below does not apply and the origin-facing list is not
   consulted.

Resolution is therefore ``sourceIp`` for every request unless the request passes the header
check below. A deployment that has CloudFront or an ALB configured still authorizes direct
execute-api callers by their own connection address, so existing direct integrations are never
broken.

``X-Forwarded-For`` is the only header read. ``CloudFront-Viewer-Address`` is not: the
deployment's distribution does not forward it to the API origin.

Header trust: ``X-Forwarded-For`` is used only as a guard for a request that API Gateway reports
with a CloudFront origin-facing address as ``sourceIp``. AWS documents ``sourceIp`` as the source
address of the immediate TCP connection; for traffic through the deployment's distribution that is
the edge, but API Gateway reports the viewer (case 3), so that traffic does not take this step.
Three conditions, all required:

- the deployment is behind CloudFront (``fronted == "cloudfront"``). On ``"alb"`` and
  ``"none"`` deployments no reverse proxy sets the header, so it is ignored entirely and the
  origin-facing list is never consulted;
- ``sourceIp`` is set and ``X-Forwarded-For`` has at least two entries, the last of which is
  exactly ``sourceIp`` and the one before it an IP address. Only a request that meets this
  consults the origin-facing list. API Gateway appends ``sourceIp`` to an ``X-Forwarded-For``
  a direct caller sends, so on a CloudFront deployment the requests that consult the list are,
  in practice, direct execute-api calls that carry their own ``X-Forwarded-For``;
- ``sourceIp`` is one of CloudFront's origin-facing addresses. A CloudFront deployment's
  execute-api endpoint stays reachable directly, and on such a request every header is
  whatever the caller sent, so a request whose ``sourceIp`` is not origin-facing is evaluated
  by ``sourceIp`` like any direct caller.

The origin-facing list is the snapshot in ``cloudFrontOriginFacingRanges.py`` (generated by
``backend/scripts/generateCloudFrontOriginFacingRanges.py`` from the published AWS IP address
ranges) united with a copy refreshed from the same document at run time when that is reachable —
see ``is_cloudfront_origin_facing``. A refresh attempt starts only from a request that consults
the list, only when its ``sourceIp`` is a valid address the snapshot does not hold, and only when
this execution environment's refresh window has elapsed (no attempt yet since the cold start,
``REFRESH_INTERVAL_SECONDS`` after a success, or the back-off wait after a failure). Traffic
through the distribution, requests without such an ``X-Forwarded-For``, and every request on an
ALB or unfronted deployment never start one. Even when ``sourceIp`` is origin-facing, only the
right-most *untrusted* forwarded address (the entry left of the trailing hop that equals
``sourceIp``) is used, so a client-supplied left-most entry can never grant access, and a header
value that does not parse as an IP address is not used.
"""
import ipaddress
import json
from time import monotonic as _monotonic
from typing import Dict, List, Optional, Tuple

import requests

from common.auth.cloudFrontOriginFacingRanges import (
    CREATE_DATE as SNAPSHOT_CREATE_DATE,
    IPV4_PREFIXES as _SNAPSHOT_IPV4_PREFIXES,
    IPV6_PREFIXES as _SNAPSHOT_IPV6_PREFIXES,
    SERVICE as ORIGIN_FACING_SERVICE,
    SOURCE_URL as ORIGIN_FACING_SOURCE_URL,
)
from customLogging.logger import safeLogger

logger = safeLogger(service_name="ClientIp")

# Run-time refresh of the CloudFront origin-facing list (see is_cloudfront_origin_facing).
# One attempt per window and no retries: the bundled snapshot answers whenever an attempt fails.
REFRESH_TIMEOUT_SECONDS = (1, 2)  # (connect, read) for the single request of an attempt
REFRESH_DOWNLOAD_SECONDS = 5  # ceiling on the whole download, on top of the per-read timeout
REFRESH_MAX_DOCUMENT_BYTES = 16 * 1024 * 1024  # the published document is about 3 MB
REFRESH_INTERVAL_SECONDS = 6 * 60 * 60  # a successful refresh is reused for 6 hours
# The wait after a failed attempt; it doubles with each further consecutive failure, up to
# REFRESH_INTERVAL_SECONDS, and returns to this value after a successful refresh.
REFRESH_RETRY_AFTER_FAILURE_SECONDS = 15 * 60


def _networks(prefixes, version: int) -> Tuple:
    """Parse prefixes into networks of one IP version, skipping any that do not parse."""
    parsed = []
    for prefix in prefixes:
        try:
            network = ipaddress.ip_network(str(prefix).strip(), strict=False)
        except (ValueError, TypeError):
            continue
        if network.version == version:
            parsed.append(network)
    return tuple(parsed)


_SNAPSHOT_NETWORKS: Dict[int, Tuple] = {
    4: _networks(_SNAPSHOT_IPV4_PREFIXES, 4),
    6: _networks(_SNAPSHOT_IPV6_PREFIXES, 6),
}

# Per execution environment: what the last successful refresh returned, when the next attempt
# may run (a time.monotonic() reading; 0 means none has run), how many attempts in a row have
# failed, and whether a failed attempt has already been logged, so a failure is logged once per
# cold start and never per request.
_refreshed_networks: Dict[int, Tuple] = {4: (), 6: ()}
_next_refresh_at = 0.0
_consecutive_refresh_failures = 0
_refresh_failure_logged = False


def _contains(networks: Dict[int, Tuple], address) -> bool:
    return any(address in network for network in networks.get(address.version, ()))


def parse_origin_facing(document) -> Optional[Dict[int, Tuple]]:
    """The origin-facing networks an ip-ranges document lists, by IP version, or None if none."""
    if not isinstance(document, dict):
        return None
    ipv4 = [
        entry.get("ip_prefix")
        for entry in document.get("prefixes") or []
        if isinstance(entry, dict) and entry.get("service") == ORIGIN_FACING_SERVICE
    ]
    ipv6 = [
        entry.get("ipv6_prefix")
        for entry in document.get("ipv6_prefixes") or []
        if isinstance(entry, dict) and entry.get("service") == ORIGIN_FACING_SERVICE
    ]
    networks = {4: _networks(ipv4, 4), 6: _networks(ipv6, 6)}
    if not networks[4] and not networks[6]:
        return None
    return networks


def _download_origin_facing() -> Dict[int, Tuple]:
    """Make one attempt at the published ranges document; raise on any failure.

    A single GET with no retries (``requests`` retries nothing by default) and no redirects, so
    the list can only come from the published location. The download is capped in size and in
    total time as well as per read.
    """
    started = _monotonic()
    response = requests.get(
        ORIGIN_FACING_SOURCE_URL,
        timeout=REFRESH_TIMEOUT_SECONDS,
        stream=True,
        allow_redirects=False,
    )
    try:
        if response.status_code != 200:
            raise ValueError(f"unexpected HTTP status {response.status_code}")
        body = bytearray()
        for chunk in response.iter_content(chunk_size=64 * 1024):
            body.extend(chunk)
            if len(body) > REFRESH_MAX_DOCUMENT_BYTES:
                raise ValueError("the ranges document exceeds the size limit")
            if _monotonic() - started > REFRESH_DOWNLOAD_SECONDS:
                raise TimeoutError("the ranges document download exceeded its time limit")
    finally:
        response.close()
    networks = parse_origin_facing(json.loads(bytes(body)))
    if networks is None:
        raise ValueError(f"the ranges document lists no {ORIGIN_FACING_SERVICE} prefixes")
    return networks


def _retry_after_failure_seconds(consecutive_failures: int) -> float:
    """The wait before the next attempt after this many failed attempts in a row (1 or more)."""
    doublings = min(max(consecutive_failures - 1, 0), 16)
    return min(REFRESH_RETRY_AFTER_FAILURE_SECONDS * 2 ** doublings, REFRESH_INTERVAL_SECONDS)


def _refresh_if_due() -> None:
    """Refresh the run-time list when its window has elapsed; never raises."""
    global _refreshed_networks, _next_refresh_at, _consecutive_refresh_failures
    global _refresh_failure_logged
    now = _monotonic()
    if now < _next_refresh_at:
        return
    try:
        networks = _download_origin_facing()
    except Exception as e:
        _consecutive_refresh_failures += 1
        _next_refresh_at = now + _retry_after_failure_seconds(_consecutive_refresh_failures)
        if not _refresh_failure_logged:
            _refresh_failure_logged = True
            logger.warning(
                "Could not refresh the CloudFront origin-facing address list "
                f"({type(e).__name__}: {e}); using the bundled snapshot dated {SNAPSHOT_CREATE_DATE}"
            )
        return
    _consecutive_refresh_failures = 0
    _refreshed_networks = networks
    _next_refresh_at = now + REFRESH_INTERVAL_SECONDS
    missing = sum(
        1
        for version, refreshed in networks.items()
        for network in refreshed
        if network not in _SNAPSHOT_NETWORKS.get(version, ())
    )
    if missing:
        logger.warning(
            f"The published CloudFront origin-facing address list has {missing} prefix(es) the "
            f"bundled snapshot dated {SNAPSHOT_CREATE_DATE} does not; regenerate it with "
            "backend/scripts/generateCloudFrontOriginFacingRanges.py"
        )


def is_cloudfront_origin_facing(address) -> bool:
    """Whether an address is one of CloudFront's origin-facing addresses.

    The bundled snapshot answers first. Only an address it does not hold consults the run-time
    list, which is refreshed from the published document at most once per
    ``REFRESH_INTERVAL_SECONDS``. Snapshot and run-time list are used as a union, so a refresh
    can only add addresses, and an environment that cannot reach the document (for example an
    authorizer in a VPC without internet egress) keeps the snapshot. After a failed attempt the
    next one waits ``REFRESH_RETRY_AFTER_FAILURE_SECONDS``, doubled for each further consecutive
    failure up to ``REFRESH_INTERVAL_SECONDS``. An address that does not parse is not
    origin-facing.
    """
    try:
        parsed = ipaddress.ip_address(str(address).strip())
    except (ValueError, TypeError):
        return False
    if _contains(_SNAPSHOT_NETWORKS, parsed):
        return True
    _refresh_if_due()
    return _contains(_refreshed_networks, parsed)


def _is_ip(value: Optional[str]) -> bool:
    try:
        ipaddress.ip_address(value)
    except (ValueError, TypeError):
        return False
    return True


def _rightmost_untrusted_xff(xff: str, trusted_peer: Optional[str]) -> Optional[str]:
    """Return the right-most X-Forwarded-For entry that we did not add (the real client).

    The entry adjacent to the gateway is the trusted proxy hop (e.g. CloudFront); the real
    client is the entry to its left. Dropping a trailing entry equal to the trusted peer
    prevents a client from spoofing access by prepending a fake left-most address.
    """
    parts = [p.strip() for p in xff.split(",") if p.strip()]
    if not parts:
        return None
    # Drop a trailing entry equal to the trusted peer (the proxy that called us).
    if trusted_peer and parts[-1] == trusted_peer:
        parts = parts[:-1]
    if not parts:
        return None
    return parts[-1]


def _forwarded_client_ip(event: dict, source_ip: str) -> Optional[str]:
    """The client address CloudFront's ``X-Forwarded-For`` names, or None if it names none.

    Says nothing about whether the header is to be believed: the caller decides that from
    ``sourceIp``. Only a header whose trailing hop is ``sourceIp`` (the proxy hop adjacent to
    the gateway) names a client, and a value that does not parse as an IP address is passed
    over. For traffic through the deployment's distribution the trailing hop is the edge while
    ``sourceIp`` is already the viewer, so this returns None.
    """
    headers = event.get("headers", {}) or {}
    if not isinstance(headers, dict):
        return None
    lower = {k.lower(): v for k, v in headers.items() if isinstance(k, str)}

    xff = lower.get("x-forwarded-for")
    if isinstance(xff, str) and xff:
        parts = [p.strip() for p in xff.split(",") if p.strip()]
        if len(parts) > 1 and parts[-1] == source_ip:
            resolved = _rightmost_untrusted_xff(xff, source_ip)
            if _is_ip(resolved):
                return resolved
    return None


def resolve_client_ip(event: dict, *, fronted: str = "none") -> Optional[str]:
    """Resolve the real client IP for an API request, adaptively per request.

    ``fronted`` is a deploy-time hint of the configured front ("cloudfront", "alb", or
    "none"). ``X-Forwarded-For`` is read **only** when ``fronted == "cloudfront"`` AND
    ``sourceIp`` is a CloudFront origin-facing address: a guard for a request API Gateway
    reports with a CloudFront edge as ``sourceIp``. Traffic through the deployment's
    distribution does not take that step, because API Gateway already reports its viewer as
    ``sourceIp`` (module docstring, case 3).
    Resolution order:

    1. (origin-facing ``sourceIp`` only) ``X-Forwarded-For`` whose trailing hop is
       ``sourceIp`` — use the right-most untrusted hop.
    2. Otherwise ``identity.sourceIp``. Authoritative for direct execute-api callers
       (including direct callers of a CloudFront deployment), ALB redirects and traffic
       through the deployment's distribution (where it is the viewer), and a client cannot
       choose it, so a forwarding header a direct caller sets cannot stand in for an
       allow-listed IP.
    """
    identity = (event.get("requestContext", {}) or {}).get("identity", {}) or {}
    source_ip = identity.get("sourceIp")

    # Only a CloudFront deployment has a reverse proxy that sets forwarding headers. On
    # "alb"/"none" every header is client-controlled, so fall straight through to ``sourceIp``.
    if fronted == "cloudfront" and source_ip:
        # Headers first, so a request that carries none never consults the address list.
        forwarded = _forwarded_client_ip(event, source_ip)
        if forwarded and is_cloudfront_origin_facing(source_ip):
            return forwarded

    # 2) sourceIp: ALB redirects, direct callers of the execute-api URL on any deployment,
    #    traffic through the distribution (reported as the viewer), and any request whose
    #    sourceIp is not origin-facing.
    return source_ip


def is_ip_authorized(source_ip: Optional[str], allowed_ranges: List) -> bool:
    """Whether a client address falls inside one of the configured ``[min, max]`` ranges.

    Ranges are inclusive and are compared numerically via ``ipaddress``, so both IPv4 and IPv6
    are expressible: ``[["203.0.113.0", "203.0.113.255"]]`` and
    ``[["2001:db8::", "2001:db8::ffff"]]`` are both valid, and a deployment may configure ranges
    of both families side by side.

    An empty range list means unrestricted. A range whose two endpoints are different families,
    or either of whose endpoints does not parse, is skipped rather than allowed — a malformed
    entry must not widen access — and a caller whose family has no configured range at all is
    logged, because that is the case where an operator has restricted by IPv4 and an IPv6 viewer
    is denied with no configuration able to admit it.
    """
    if not allowed_ranges:
        return True
    if not source_ip:
        return False

    try:
        source = ipaddress.ip_address(str(source_ip).strip())
    except (ValueError, TypeError):
        # Fail closed: an address this function cannot parse must not be admitted, and must not
        # raise into the authorizer either, where it would answer 500 instead of denying.
        logger.warning("Client address is not a valid IP address; denying")
        return False

    family_has_a_range = False
    for entry in allowed_ranges:
        try:
            min_ip, max_ip = entry
            low = ipaddress.ip_address(str(min_ip).strip())
            high = ipaddress.ip_address(str(max_ip).strip())
        except (ValueError, TypeError):
            logger.warning("Skipping malformed allowed IP range entry")
            continue

        if low.version != high.version:
            logger.warning("Skipping allowed IP range whose endpoints are different IP versions")
            continue
        if low.version != source.version:
            continue

        family_has_a_range = True
        if low <= source <= high:
            return True

    if not family_has_a_range:
        logger.warning(
            f"No allowed IP range is configured for IPv{source.version}, so every caller of that "
            f"family is denied. Add an IPv{source.version} range to "
            "authorizerOptions.allowedIpRanges."
        )
    return False
