"""Regenerate ``cloudFrontOriginFacingRanges.py`` from the published AWS IP address ranges.

The REST authorizer uses Amazon CloudFront's ``X-Forwarded-For`` only for a request that Amazon API
Gateway reports with one of CloudFront's origin-facing addresses as ``sourceIp``
(``backend/backend/common/auth/clientIp.py``). It
refreshes that list at run time when it can, and falls back to the snapshot this script writes when
it cannot -- so the snapshot is what a deployment relies on when the authorizer has no route to the
internet. Regenerate it when preparing a release and commit the result::

    # from the repository root; fetches https://ip-ranges.amazonaws.com/ip-ranges.json
    python backend/scripts/generateCloudFrontOriginFacingRanges.py

    # or from a copy of the document downloaded separately
    python backend/scripts/generateCloudFrontOriginFacingRanges.py --input ip-ranges.json

The output is written to ``backend/backend/common/auth/cloudFrontOriginFacingRanges.py`` unless
``--output`` names another path. This script lives outside ``backend/backend`` so that it is not
packaged into the Lambda functions. Standard library only, so it runs without the backend's
dependencies installed.
"""
import argparse
import ipaddress
import json
import os
import sys
import urllib.request

SOURCE_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json"
SERVICE = "CLOUDFRONT_ORIGIN_FACING"
OUTPUT_FILE_NAME = "cloudFrontOriginFacingRanges.py"
DEFAULT_OUTPUT = os.path.normpath(
    os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "backend", "common", "auth", OUTPUT_FILE_NAME
    )
)

_FETCH_TIMEOUT_SECONDS = 30

_HEADER = '''# Copyright 2026 Amazon.com, Inc. or its affiliates. All Rights Reserved.
# SPDX-License-Identifier: Apache-2.0
"""Amazon CloudFront origin-facing address prefixes: a generated snapshot.

GENERATED by backend/scripts/generateCloudFrontOriginFacingRanges.py. Do not edit by hand:
regenerate it with that script from the repository root and commit the result.

Source: {source_url}, service {service}
createDate: {create_date}

``clientIp.py`` uses CloudFront's X-Forwarded-For only for a request whose ``sourceIp`` falls in
one of these prefixes or in the list it refreshes from the source at run time.
"""

SOURCE_URL = "{source_url}"
SERVICE = "{service}"
CREATE_DATE = "{create_date}"
'''


def extract_origin_facing(document):
    """Return ``(create_date, ipv4_prefixes, ipv6_prefixes)`` for the origin-facing service.

    Each prefix list is de-duplicated and sorted by network. Fails loudly rather than writing a
    partial snapshot: a document without a ``createDate``, a prefix that does not parse as a network
    of its family, or a family with no origin-facing prefix at all raises ``ValueError``.
    """
    if not isinstance(document, dict):
        raise ValueError("the ranges document is not a JSON object")
    create_date = document.get("createDate")
    if not isinstance(create_date, str) or not create_date.strip():
        raise ValueError("the ranges document has no createDate")

    families = (
        ("prefixes", "ip_prefix", ipaddress.IPv4Network),
        ("ipv6_prefixes", "ipv6_prefix", ipaddress.IPv6Network),
    )
    extracted = []
    for list_key, prefix_key, network_type in families:
        networks = set()
        for entry in document.get(list_key) or []:
            if not isinstance(entry, dict) or entry.get("service") != SERVICE:
                continue
            networks.add(network_type(entry.get(prefix_key)))
        if not networks:
            raise ValueError(f"the ranges document lists no {SERVICE} entries in {list_key}")
        extracted.append([str(network) for network in sorted(networks)])
    return create_date.strip(), extracted[0], extracted[1]


def _render_tuple(name, prefixes):
    lines = [f"{name} = ("]
    lines.extend(f'    "{prefix}",' for prefix in prefixes)
    lines.append(")")
    return "\n".join(lines) + "\n"


def render_module(create_date, ipv4_prefixes, ipv6_prefixes):
    """The full text of ``cloudFrontOriginFacingRanges.py`` for the given snapshot."""
    header = _HEADER.format(source_url=SOURCE_URL, service=SERVICE, create_date=create_date)
    return "\n".join(
        [
            header,
            _render_tuple("IPV4_PREFIXES", ipv4_prefixes),
            _render_tuple("IPV6_PREFIXES", ipv6_prefixes),
        ]
    )


def _load_document(input_path):
    if input_path:
        with open(input_path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    # SOURCE_URL is the module's https constant; no part of the URL comes from input.
    # nosemgrep: python.lang.security.audit.dynamic-urllib-use-detected.dynamic-urllib-use-detected
    with urllib.request.urlopen(  # nosec B310 - constant https URL
        SOURCE_URL, timeout=_FETCH_TIMEOUT_SECONDS
    ) as response:
        return json.loads(response.read())


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", help="read this local copy of ip-ranges.json instead of fetching it")
    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT,
        help=f"where to write the module (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args(argv)

    create_date, ipv4_prefixes, ipv6_prefixes = extract_origin_facing(_load_document(args.input))
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_module(create_date, ipv4_prefixes, ipv6_prefixes))
    sys.stderr.write(
        f"Wrote {args.output}: createDate {create_date}, "
        f"{len(ipv4_prefixes)} IPv4 and {len(ipv6_prefixes)} IPv6 prefixes\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
