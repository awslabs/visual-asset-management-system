/**
 * The large object copy engine (lib/lambdaBuilder/assetFunctions.ts) in every partition
 * template, with the Lambdas in the VPC, and with a deployment config that still carries the removed
 * app.largeFileIngestion block (ignored).
 *
 * Contracts pinned here:
 * - throttling never ends a copy early: every engine task retries Lambda.TooManyRequestsException
 *   with its own long jittered retrier, ahead of the fault retrier (a throttled copy waits for
 *   capacity instead of failing and discarding its partial upload);
 * - a notify that exhausted its retries gets a last, longer attempt, so a landed file still reports;
 * - the copy fan-out is bounded: the Map's MaxConcurrency is the fixed MAX_CONCURRENT_BATCHES (10,
 *   the backend's MAX_CONCURRENT_BATCHES), and the function is unreserved;
 * - the engine's sizes, batching and wait are backend constants: no tuning environment variable;
 * - the function is sized for server-side copies unless the Lambdas run in the VPC (streamed parts);
 * - failed copy executions raise an alarm, and so does a request in the reconcile dead-letter queue.
 * The workflow side (process-output, AwaitOutputIngestion, FinalizeOutputs) is generated by the backend
 * and pinned in backend/tests/common/workflows/test_workflowAsl_output_ingestion.py.
 */

