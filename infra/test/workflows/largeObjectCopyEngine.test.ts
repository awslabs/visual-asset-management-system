        expect(partsStates.LargeObjectCopyBatches.MaxConcurrency).toBe(MAX_CONCURRENT_BATCHES);
        expect(MAX_CONCURRENT_BATCHES).toBe(10);
        expect(partsStates.LargeObjectCopyBatches.MaxConcurrencyPath).toBeUndefined();
        expect(jobStates.LargeObjectCopyChunks.MaxConcurrency).toBe(1);
