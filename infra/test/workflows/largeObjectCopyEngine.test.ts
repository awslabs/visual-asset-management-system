    const handWrittenManagedPoliciesOf = (roleId: string) =>
        managedPoliciesOf(roleId).filter(([id]) => !/OverflowPolicy\d+[0-9A-F]{8}$/.test(id));
    /** The role's own statements: its inline documents and CDK's overflow policies of it. */
