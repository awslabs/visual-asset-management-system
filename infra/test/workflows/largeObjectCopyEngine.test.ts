/**
 * The large object copy engine (lib/lambdaBuilder/largeObjectCopyEngine.ts) in every partition
 * template, with the Lambdas in the VPC, and with a reserved concurrency.
 *
 * Contracts pinned here:
 * - throttling never ends a copy early: every engine task retries Lambda.TooManyRequestsException
 *   with its own long jittered retrier, ahead of the fault retrier (a throttled copy waits for
 *   capacity instead of failing and discarding its partial upload);
 * - a notify that exhausted its retries gets a last, longer attempt, so a landed file still reports;
 * - the copy fan-out is bounded: the Map's MaxConcurrency comes from maxConcurrentBatches (default
 *   10), and engineReservedConcurrency, when set, caps the function deployment-wide;
 * - the function is sized for server-side copies unless the Lambdas run in the VPC (streamed parts);
 * - failed copy executions raise an alarm, and so does a request in the reconcile dead-letter queue.
 * The workflow side (process-output, AwaitOutputIngestion, FinalizeOutputs) is generated by the backend
 * and pinned in backend/tests/common/workflows/test_workflowAsl_output_ingestion.py.
 */

import * as fs from "fs";
import * as path from "path";
import * as Config from "../../config/config";
import {
    BATCHES_PER_CHUNK,
    CHUNK_START_RETRY,
    FAULT_RETRY,
    HISTORY_EVENT_QUOTA,
    LARGE_OBJECT_COPY_RECONCILE_DLQ_ALARM_ID,
    LARGE_OBJECT_COPY_RECONCILE_DLQ_ID,
    LARGE_OBJECT_COPY_RECONCILE_STATUSES,
    LARGE_OBJECT_COPY_SERVER_SIDE_MEMORY_MB,
    MAP_ITERATION_EVENTS,
    MAX_BATCHES,
    NOTIFY_LAST_ATTEMPT_RETRY,
    THROTTLE_RETRY,
    worstCaseTaskEvents,
} from "../../lib/lambdaBuilder/largeObjectCopyEngine";
import { SynthResult, TemplateName, synthTemplate } from "../support/templateSynth";
import { nestedTemplateKeyFor } from "../support/iamPolicySize";

jest.setTimeout(900_000);

interface Cell {
    name: string;
    template: TemplateName;
    vpc?: boolean;
    reserved?: number;
}

const CELLS: Cell[] = [
    { name: "commercial", template: "commercial" },
    { name: "commercial-vpc-reserved", template: "commercial", vpc: true, reserved: 50 },
    { name: "govcloud", template: "govcloud" },
    { name: "eusovereign", template: "eusovereign" },
];

function synthCell(cell: Cell): SynthResult {
    if (!cell.vpc && !cell.reserved) {
        return synthTemplate(cell.template);
    }
    return synthTemplate(cell.template, {
        mutate: (c) => {
            if (cell.vpc) {
                c.app.useGlobalVpc.enabled = true;
                c.app.useGlobalVpc.useForAllLambdas = true;
            }
            if (cell.reserved) {
                c.app.largeFileIngestion = {
                    ...(c.app.largeFileIngestion ?? {}),
                    engineReservedConcurrency: cell.reserved,
                };
            }
        },
        mutateKey: cell.name,
    });
}

function byPrefix(resources: Record<string, any>, type: string, prefix: string) {
    return Object.entries(resources).filter(
        ([id, r]) => r.Type === type && new RegExp(`^${prefix}[0-9A-F]{8}$`).test(id)
    );
}

function allStates(states: Record<string, any>): Record<string, any> {
    const out: Record<string, any> = {};
    for (const [id, state] of Object.entries(states)) {
        out[id] = state;
        const nested = state.ItemProcessor?.States ?? state.Iterator?.States;
        if (nested) Object.assign(out, allStates(nested));
    }
    return out;
}

const isLambdaTask = (s: any) =>
    s.Type === "Task" && JSON.stringify(s.Resource).includes(":lambda:invoke");

describe.each(CELLS)("large object copy engine ($name)", (cell) => {
    let resources: Record<string, any>;
    let definition: any;
    let partsDefinition: any;
    let engineFunction: any;
    let engineFunctionId: string;
    let stateMachineId: string;
    let jobStates: Record<string, any>;
    let partsStates: Record<string, any>;
    let states: Record<string, any>;

    beforeAll(() => {
        const synth = synthCell(cell);
        resources = synth.templates[nestedTemplateKeyFor(synth, "ApiBuilder2")].Resources;
        const machines = byPrefix(
            resources,
            "AWS::StepFunctions::StateMachine",
            "LargeObjectCopyStateMachine"
        );
        expect(machines).toHaveLength(1);
        stateMachineId = machines[0][0];
        definition = JSON.parse(SynthResult.flatten(machines[0][1].Properties.DefinitionString));
        const parts = byPrefix(
            resources,
            "AWS::StepFunctions::StateMachine",
            "LargeObjectCopyPartsStateMachine"
        );
        expect(parts).toHaveLength(1);
        partsDefinition = JSON.parse(SynthResult.flatten(parts[0][1].Properties.DefinitionString));
        const functions = byPrefix(resources, "AWS::Lambda::Function", "largeObjectCopy");
        expect(functions).toHaveLength(1);
        engineFunctionId = functions[0][0];
        engineFunction = functions[0][1];
        jobStates = allStates(definition.States);
        partsStates = allStates(partsDefinition.States);
        states = { ...jobStates, ...partsStates };
    });

    test("every engine task waits out throttling with its own long retrier, ahead of faults", () => {
        const tasks = Object.entries(states).filter(([, s]) => isLambdaTask(s));
        expect(tasks.length).toBeGreaterThanOrEqual(8);
        for (const [id, task] of tasks) {
            const retry = task.Retry as any[];
            const throttleIndex = retry.findIndex((r) =>
                r.ErrorEquals.includes("Lambda.TooManyRequestsException")
            );
            const allIndex = retry.findIndex((r) => r.ErrorEquals.includes("States.ALL"));
            expect({ id, throttleIndex: throttleIndex >= 0 }).toEqual({ id, throttleIndex: true });
            expect(throttleIndex).toBeLessThan(allIndex);
            const throttle = retry[throttleIndex];
            expect(throttle.ErrorEquals).toEqual(THROTTLE_RETRY.errors);
            expect(throttle.MaxAttempts).toBe(THROTTLE_RETRY.maxAttempts);
            expect(throttle.MaxDelaySeconds).toBe(THROTTLE_RETRY.maxDelaySeconds);
            expect(throttle.JitterStrategy).toBe("FULL");
            // A named refusal is still final.
            expect(retry[0]).toEqual(
                expect.objectContaining({ ErrorEquals: ["CopyRefused", "SourceChanged"] })
            );
        }
        let waited = 0;
        for (let n = 0; n < THROTTLE_RETRY.maxAttempts; n++) {
            waited += Math.min(
                THROTTLE_RETRY.intervalSeconds * THROTTLE_RETRY.backoffRate ** n,
                THROTTLE_RETRY.maxDelaySeconds
            );
        }
        expect(waited).toBeGreaterThan(6 * 3600);
    });

    test("the copy batches keep their fault retrier and the copy's concurrency is bounded", () => {
        // The batches run in the child state machine, which runs maxConcurrentBatches at once; the
        // job's execution runs one chunk (one child execution) at a time.
        expect(partsStates.LargeObjectCopyBatches.MaxConcurrency).toBe(
            Config.LARGE_FILE_INGESTION_DEFAULTS.maxConcurrentBatches
        );
        expect(Config.LARGE_FILE_INGESTION_DEFAULTS.maxConcurrentBatches).toBe(10);
        expect(jobStates.LargeObjectCopyChunks.MaxConcurrency).toBe(1);
        expect(jobStates.LargeObjectCopyBatch).toBeUndefined();
        const fault = (partsStates.LargeObjectCopyBatch.Retry as any[]).find((r) =>
            r.ErrorEquals.includes("States.ALL")
        );
        expect(fault.MaxAttempts).toBe(FAULT_RETRY.maxAttempts);
    });

    test("each chunk runs as a child execution that the job's execution waits on", () => {
        const chunk = jobStates.LargeObjectCopyChunk;
        expect(JSON.stringify(chunk.Resource)).toContain(":states:startExecution.sync:2");
        expect(chunk.Parameters.Input["AWS_STEP_FUNCTIONS_STARTED_BY_EXECUTION_ID.$"]).toBe(
            "$$.Execution.Id"
        );
        // Only a failed start is retried; a failed child execution (a refusal, or a batch that
        // exhausted its retries) is final and goes to the failure path.
        expect(chunk.Retry).toEqual([
            expect.objectContaining({
                ErrorEquals: [
                    "StepFunctions.ExecutionLimitExceeded",
                    "StepFunctions.ThrottlingException",
                ],
                MaxAttempts: CHUNK_START_RETRY.maxAttempts,
            }),
        ]);
        // A wildcard would also match a failed child execution and re-run the chunk.
        const retried = JSON.stringify(chunk.Retry.map((r: any) => r.ErrorEquals));
        expect(retried).not.toContain("States.ALL");
        expect(retried).not.toContain("States.TaskFailed");
        expect(jobStates.LargeObjectCopyChunks.Catch[0].Next).toBe("LargeObjectCopyFail");
        expect(jobStates.LargeObjectCopyPrepare.ResultSelector["chunks.$"]).toBe(
            "$.Payload.chunks"
        );
        expect(
            engineFunction.Properties.Environment.Variables.LARGE_OBJECT_COPY_BATCHES_PER_CHUNK
        ).toBe(String(BATCHES_PER_CHUNK));
    });

    test("no execution of a copy can reach the history quota (H2)", () => {
        // Child execution: BATCHES_PER_CHUNK iterations of CopyBatch with every retrier exhausted,
        // plus its start, Map and end events.
        const perBatch =
            MAP_ITERATION_EVENTS + worstCaseTaskEvents(partsStates.LargeObjectCopyBatch.Retry);
        expect(perBatch).toBe(322);
        const child = BATCHES_PER_CHUNK * perBatch + 10;
        expect(child).toBeLessThan(HISTORY_EVENT_QUOTA * 0.7);

        // Job execution: every chunk of the largest plan, plus each other task once with every
        // retrier exhausted, plus its Pass, Choice, Map and end events.
        const chunks = Math.ceil(MAX_BATCHES / BATCHES_PER_CHUNK);
        const perChunk =
            MAP_ITERATION_EVENTS + worstCaseTaskEvents(jobStates.LargeObjectCopyChunk.Retry, true);
        const others = Object.entries(jobStates)
            .filter(([id, s]) => s.Type === "Task" && id !== "LargeObjectCopyChunk")
            .reduce((sum, [, s]) => sum + worstCaseTaskEvents(s.Retry ?? []), 0);
        const job = chunks * perChunk + others + 2 * Object.keys(jobStates).length;
        expect(job).toBeLessThan(HISTORY_EVENT_QUOTA * 0.2);

        // Before this change the batches ran inline: the job's own history held every batch.
        expect(MAX_BATCHES * perBatch).toBeGreaterThan(HISTORY_EVENT_QUOTA);
    });

    test("the chunk and batch limits match the backend planner", () => {
        const backend = fs.readFileSync(
            path.join(__dirname, "../../../backend/backend/common/largeObjectCopy.py"),
            "utf8"
        );
        expect(backend).toMatch(new RegExp(`^MAX_BATCHES = ${MAX_BATCHES}$`, "m"));
        expect(backend).toMatch(
            new RegExp(`^DEFAULT_BATCHES_PER_CHUNK = ${BATCHES_PER_CHUNK}$`, "m")
        );
    });

    test("a refused file ends in its own state, not the failed state the alarm counts", () => {
        expect(jobStates.LargeObjectCopyFail.ResultPath).toBe("$.outcome");
        expect(jobStates.LargeObjectCopyNotifyFailed.Next).toBe("LargeObjectCopyRefusedOrFailed");
        expect(jobStates.LargeObjectCopyNotifyFailedLastAttempt.Next).toBe(
            "LargeObjectCopyRefusedOrFailed"
        );
        const choice = jobStates.LargeObjectCopyRefusedOrFailed;
        expect(choice.Choices[0].Next).toBe("LargeObjectCopyRefused");
        expect(JSON.stringify(choice.Choices[0])).toContain("$.outcome.refused");
        expect(choice.Default).toBe("LargeObjectCopyFailed");
        expect(jobStates.LargeObjectCopyRefused.Type).toBe("Succeed");
        expect(jobStates.LargeObjectCopyFailed.Type).toBe("Fail");
    });

    test("a copy execution that ends outside its states is reconciled", () => {
        const rules = byPrefix(resources, "AWS::Events::Rule", "LargeObjectCopyStatusChangeRule");
        expect(rules).toHaveLength(1);
        const rule = rules[0][1].Properties;
        expect(rule.EventPattern.source).toEqual(["aws.states"]);
        expect(rule.EventPattern.detail.status).toEqual(LARGE_OBJECT_COPY_RECONCILE_STATUSES);
        // This deployment's copy state machine only, never its child state machine or a workflow.
        const arns = JSON.stringify(rule.EventPattern.detail.stateMachineArn);
        expect(arns).toContain("LargeObjectCopy-");
        expect(arns).not.toContain("LargeObjectCopyParts-");
        const target = rule.Targets[0];
        expect(JSON.stringify(target.Arn)).toContain(engineFunctionId);
        expect(target.DeadLetterConfig).toBeDefined();
        expect(target.RetryPolicy).toEqual({
            MaximumEventAgeInSeconds: 7200,
            MaximumRetryAttempts: 3,
        });
        // Failed asynchronous reconcile invocations are kept, not dropped.
        expect(engineFunction.Properties.DeadLetterConfig).toBeDefined();
        const dlqs = byPrefix(resources, "AWS::SQS::Queue", "LargeObjectCopyReconcileDLQ");
        expect(dlqs).toHaveLength(1);
    });

    test("the engine can describe its executions and the details read can hand it one", () => {
        const policies = JSON.stringify(
            Object.values(resources).filter(
                (r: any) => r.Type === "AWS::IAM::Policy" || r.Type === "AWS::IAM::ManagedPolicy"
            )
        );
        expect(policies).toContain("states:DescribeExecution");
        expect(policies).toContain("LargeObjectCopy-");
    });

    // #1123 M11 round 6: every function that stops copies hands them to the engine's reconcile.
    const handlerOf = (r: any) => String(r.Properties?.Handler ?? "");
    // The function built under that handler's own construct id (the execution service's
    // permanent-delete route set shares its handler under another id).
    const functionByHandler = (suffix: string) => {
        const name = suffix
            .replace(/\.lambda_handler$/, "")
            .split(".")
            .pop();
        const found = Object.entries(resources).filter(
            ([id, r]: [string, any]) =>
                r.Type === "AWS::Lambda::Function" &&
                handlerOf(r).endsWith(suffix) &&
                new RegExp(`^${name}[0-9A-F]{8}$`).test(id)
        );
        expect(found).toHaveLength(1);
        return found[0] as [string, any];
    };
    const roleIdOf = (fn: any) => fn.Properties.Role["Fn::GetAtt"][0];
    const engineArn = () => ({ "Fn::GetAtt": [engineFunctionId, "Arn"] });
    const invokesEngine = (doc: any) =>
        (doc.Statement as any[]).some(
            (s) =>
                s.Action === "lambda:InvokeFunction" &&
                JSON.stringify(s.Resource) === JSON.stringify(engineArn())
        );
    const managedPoliciesOf = (roleId: string) =>
        Object.entries(resources).filter(([id, r]: [string, any]) => {
            if (r.Type !== "AWS::IAM::ManagedPolicy") return false;
            const viaPolicy = JSON.stringify(r.Properties.Roles ?? []).includes(`"${roleId}"`);
            const viaRole = JSON.stringify(
                resources[roleId].Properties.ManagedPolicyArns ?? []
            ).includes(`"${id}"`);
            return viaPolicy || viaRole;
        });

    test.each([
        ["executionService.lambda_handler", "the abort route and the status change handler"],
        ["sfn.handleExecutionError.lambda_handler", "the error handler"],
    ])("%s (%s) takes the engine name and may invoke it", (handler) => {
        const [, fn] = functionByHandler(handler);
        expect(fn.Properties.Environment.Variables.LARGE_OBJECT_COPY_FUNCTION_NAME).toEqual({
            Ref: engineFunctionId,
        });
        const docs = managedPoliciesOf(roleIdOf(fn)).map(
            ([, r]: [string, any]) => r.Properties.PolicyDocument
        );
        expect(docs.some(invokesEngine)).toBe(true);
    });

    test("the output step reads the engine name from SSM and may invoke it, with no cycle", () => {
        const [fnId, fn] = functionByHandler("sfn.processWorkflowExecutionOutput.lambda_handler");
        const vars = fn.Properties.Environment.Variables;
        // A plain string, not a reference: the engine already references the output step.
        expect(vars.LARGE_OBJECT_COPY_FUNCTION_NAME).toBeUndefined();
        expect(typeof vars.LARGE_OBJECT_COPY_FUNCTION_NAME_PARAMETER).toBe("string");
        expect(vars.LARGE_OBJECT_COPY_FUNCTION_NAME_PARAMETER).toMatch(
            /^\/[^/]+\/largeObjectCopy\/engineFunctionName$/
        );
        const params = Object.entries(resources).filter(
            ([, r]: [string, any]) =>
                r.Type === "AWS::SSM::Parameter" &&
                r.Properties.Name === vars.LARGE_OBJECT_COPY_FUNCTION_NAME_PARAMETER
        );
        expect(params).toHaveLength(1);
        const [paramId, param] = params[0] as [string, any];
        expect(param.Properties.Type).toBe("String");
        expect(param.Properties.Value).toEqual({ Ref: engineFunctionId });
        const roleId = roleIdOf(fn);
        const handOff = Object.entries(resources).filter(
            ([, r]: [string, any]) =>
                r.Type === "AWS::IAM::ManagedPolicy" &&
                JSON.stringify(r.Properties.Roles ?? []) === JSON.stringify([{ Ref: roleId }]) &&
                invokesEngine(r.Properties.PolicyDocument)
        );
        expect(handOff).toHaveLength(1);
        const [handOffId, policy] = handOff[0] as [string, any];
        const statements = policy.Properties.PolicyDocument.Statement as any[];
        expect(statements).toHaveLength(2);
        expect(statements).toContainEqual(
            expect.objectContaining({
                Action: "ssm:GetParameter",
                Effect: "Allow",
                Resource: expect.anything(),
            })
        );
        expect(
            JSON.stringify(statements.find((s) => s.Action === "ssm:GetParameter").Resource)
        ).toContain(paramId);
        // Not attached through the role and not awaited by the function: either would close a
        // dependency cycle with the engine (which references the output step).
        expect(JSON.stringify(resources[roleId].Properties.ManagedPolicyArns ?? [])).not.toContain(
            handOffId
        );
        expect(JSON.stringify(fn.DependsOn ?? [])).not.toContain(handOffId);
        expect(JSON.stringify(engineFunction)).toContain(fnId);
    });

    test("a notify that exhausted its retries gets a longer last attempt", () => {
        for (const outcome of ["Succeeded", "Failed"]) {
            const notify = states[`LargeObjectCopyNotify${outcome}`];
            const last = `LargeObjectCopyNotify${outcome}LastAttempt`;
            expect(notify.Catch).toEqual([
                { ErrorEquals: ["States.ALL"], Next: last, ResultPath: "$.notifyError" },
            ]);
            const lastState = states[last];
            expect(lastState.Parameters.Payload.action).toBe("notify");
            expect(lastState.Parameters.Payload.status).toBe(outcome.toUpperCase());
            const fault = (lastState.Retry as any[]).find((r) =>
                r.ErrorEquals.includes("States.ALL")
            );
            expect(fault.MaxAttempts).toBe(NOTIFY_LAST_ATTEMPT_RETRY.maxAttempts);
            expect(lastState.Catch[0].Next).toBe("LargeObjectCopyNotifyLost");
        }
        expect(states.LargeObjectCopyNotifyLost.Type).toBe("Fail");
    });

    test("the function is sized for its copy path and reserved only when configured", () => {
        const props = engineFunction.Properties;
        expect(props.MemorySize).toBe(
            cell.vpc ? Config.LAMBDA_MEMORY_SIZE : LARGE_OBJECT_COPY_SERVER_SIDE_MEMORY_MB
        );
        if (cell.reserved) {
            expect(props.ReservedConcurrentExecutions).toBe(cell.reserved);
        } else {
            expect(props.ReservedConcurrentExecutions).toBeUndefined();
        }
    });

    test("failed copy executions raise an alarm", () => {
        const alarms = byPrefix(
            resources,
            "AWS::CloudWatch::Alarm",
            "LargeObjectCopyExecutionsFailedAlarm"
        );
        expect(alarms).toHaveLength(1);
        const alarm = alarms[0][1].Properties;
        expect(alarm.MetricName).toBe("ExecutionsFailed");
        expect(alarm.Namespace).toBe("AWS/States");
        expect(JSON.stringify(alarm.Dimensions)).toContain(stateMachineId);
        expect(alarm.AlarmActions).toBeUndefined();
    });

    test("a request in the reconcile dead-letter queue raises an alarm (#1123 M11)", () => {
        const queues = byPrefix(resources, "AWS::SQS::Queue", LARGE_OBJECT_COPY_RECONCILE_DLQ_ID);
        expect(queues).toHaveLength(1);
        const queueId = queues[0][0];
        // The engine's asynchronous invocations (the rule's and the details read's) dead-letter here.
        expect(JSON.stringify(engineFunction.Properties.DeadLetterConfig)).toContain(queueId);
        const alarms = byPrefix(
            resources,
            "AWS::CloudWatch::Alarm",
            LARGE_OBJECT_COPY_RECONCILE_DLQ_ALARM_ID
        );
        expect(alarms).toHaveLength(1);
        const alarm = alarms[0][1].Properties;
        expect(alarm.Namespace).toBe("AWS/SQS");
        expect(alarm.MetricName).toBe("ApproximateNumberOfMessagesVisible");
        expect(alarm.Statistic).toBe("Maximum");
        expect(alarm.Period).toBe(300);
        expect(alarm.Threshold).toBe(0);
        expect(alarm.ComparisonOperator).toBe("GreaterThanThreshold");
        expect(alarm.EvaluationPeriods).toBe(1);
        expect(alarm.TreatMissingData).toBe("notBreaching");
        expect(JSON.stringify(alarm.Dimensions)).toContain(queueId);
        expect(JSON.stringify(alarm.AlarmName)).toContain("-largeObjectCopyReconcileDLQ");
        expect(alarm.AlarmActions).toBeUndefined();
        // The remedy it names works (L15): re-invoke the reconcile. The queue has no source queue
        // to redrive to, and the details read does not check an ended run's copies.
        expect(alarm.AlarmDescription).toContain('{"action": "reconcile", "executionArn":');
        expect(alarm.AlarmDescription).not.toMatch(/redrive the queue|open the workflow execution/);
    });
});

describe("app.largeFileIngestion.engineReservedConcurrency validation", () => {
    const withValue = (value: unknown) =>
        ({
            app: {
                largeFileIngestion: {
                    ...Config.LARGE_FILE_INGESTION_DEFAULTS,
                    engineReservedConcurrency: value,
                },
            },
        } as unknown as Config.ConfigPublic);

    test.each([0, 1, 1000])("accepts %p", (value) => {
        expect(() => Config.validateLargeFileIngestionConfig(withValue(value))).not.toThrow();
    });

    test.each([-1, 1001, 2.5, "10"])("rejects %p", (value) => {
        expect(() => Config.validateLargeFileIngestionConfig(withValue(value))).toThrow(
            /app\.largeFileIngestion\.engineReservedConcurrency must be a whole number/
        );
    });

    test("defaults to unreserved", () => {
        const config = { app: {} } as unknown as Config.ConfigPublic;
        Config.applyLargeFileIngestionDefaults(config);
        expect(config.app.largeFileIngestion.engineReservedConcurrency).toBe(0);
    });
});
