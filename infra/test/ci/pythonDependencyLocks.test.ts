/**
 * Every Python dependency file in the repository is audited by the `python-dependency-audit` CI job,
 * or is listed as an exemption with a reason. Dependency files are pyproject.toml files that declare
 * dependencies, pip requirements-style files (requirements*.txt, *.in, pip-compile *.lock,
 * constraints, a requirements/ folder), Pipfiles, and setup.py or setup.cfg with install_requires.
 *
 * The job audits each directory that has a tracked uv.lock, found with `git ls-files`. A new Lambda
 * layer, pipeline, container or package that adds a pyproject.toml or requirements file without a
 * uv.lock would not be audited, so this test fails until the author adds the lock (and the job then
 * covers it with no workflow edit) or adds a reasoned entry to `.github/python-lock-exemptions.json`.
 *
 * It also checks the audit allowlist `.github/python-audit-allowlist.json`: each entry needs a
 * reason, a review date that has not passed and the uv projects it applies to. The job itself fails
 * an entry that matches no current finding in one of its projects, because only a live audit knows
 * the findings; the audit's matching is run here on small trees with the findings supplied.
 */

