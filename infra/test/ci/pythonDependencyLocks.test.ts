/**
 * Every Python dependency file in the repository is audited by the `python-dependency-audit` CI job,
 * or is listed as an exemption with a reason. Dependency files are pyproject.toml files that declare
 * dependencies, pip requirements-style files (requirements*.txt, *.in, pip-compile *.lock,
 * constraints, a requirements/ folder), Pipfiles, and setup.py or setup.cfg with install_requires.
 *
 * The job audits each directory that has a tracked uv.lock, found with `git ls-files`. A new Lambda
 * layer, pipeline, container or package that adds a pyproject.toml or requirements file without a
 * uv.lock would not be audited, so this test fails until the author adds the lock (and the job then
 * covers it with no workflow edit) or adds a reasoned entry to `.github/python-lock-exemptions.json`.
 *
 * It also checks the audit allowlist `.github/python-audit-allowlist.json`: each entry needs a
 * reason and a review date that has not passed. The job itself fails an entry that matches no
 * current finding, because only a live audit knows the findings.
 */

import { execFileSync } from "child_process";
import * as path from "path";
import { REPO_ROOT, read } from "../docs/support/docsText";

const EXEMPTIONS = ".github/python-lock-exemptions.json";
const ALLOWLIST = ".github/python-audit-allowlist.json";

interface Exemption {
    path: string;
    reason: string;
    plannedIn: string;
}

interface AllowlistEntry {
    id: string;
    package: string;
    reason: string;
    reviewBy: string;
}

/** Tracked files, relative to the VAMS root; undefined when git is unavailable (a source archive). */
function trackedFiles(): string[] | undefined {
    try {
        return execFileSync("git", ["ls-files", "-z"], {
            cwd: REPO_ROOT,
            encoding: "utf8",
            maxBuffer: 64 * 1024 * 1024,
            stdio: ["ignore", "pipe", "ignore"],
        })
            .split("\0")
            .filter((p) => p !== "");
    } catch {
        return undefined;
    }
}

/** The export header every uv-exported requirements file starts with. */
export const UV_EXPORT_HEADER = "# This file was autogenerated by uv via the following command:";

/**
 * A top-level `requirements*.txt` or `requirements*.lock`: the only dependency files a locked directory may
 * hold beside its pyproject. A `.lock` is the hashed export a container Dockerfile installs with
 * `pip install --require-hashes`; it must carry the uv export header like any other export.
 */
const isUvExportName = (file: string): boolean =>
    /^requirements[^/]*\.(txt|lock)$/.test(path.posix.basename(file));

/**
 * A pip requirements-style file: any `.txt`, `.in` or `.lock` whose name contains `requirements`
 * (`requirements-dev.txt`, `dev-requirements.txt`, a pip-compile `requirements.lock`; beside a uv.lock only
 * a uv export is covered), a
 * `constraints*.txt`, any `.txt` or `.in` inside a `requirements/` folder, or any other `.in` file
 * except setuptools' `MANIFEST.in`. `uv.lock` is not one.
 */
export const isRequirementsStyleFile = (file: string): boolean => {
    const base = path.posix.basename(file);
    const dir = path.posix.basename(path.posix.dirname(file));
    return (
        /requirements[^/]*\.(txt|in|lock)$/i.test(base) ||
        /^constraints[^/]*\.txt$/i.test(base) ||
        (dir === "requirements" && /\.(txt|in)$/i.test(base)) ||
        (/\.in$/i.test(base) && base !== "MANIFEST.in")
    );
};

/** A requirements file with at least one line that is not blank or a comment. */
export const hasRequirementLines = (text: string): boolean =>
    text.split("\n").some((line) => line.trim() !== "" && !line.trim().startsWith("#"));

/**
 * A pyproject.toml that declares dependencies: a non-empty `[project] dependencies` list, dependencies
 * declared `dynamic`, a `[dependency-groups]` table, optional dependencies, Poetry dependency tables
 * (including the old `dev-dependencies`), or uv's legacy `dev-dependencies` list.
 */
export const declaresDependencies = (text: string): boolean =>
    /^\s*(dev-)?dependencies\s*=\s*\[\s*(#[^\n]*\n\s*)*["']/m.test(text) ||
    /^\s*dynamic\s*=\s*\[[^\]]*["'](dependencies|optional-dependencies)["']/m.test(text) ||
    /^\[(dependency-groups|project\.optional-dependencies|tool\.poetry(\.group\.[^\]]+)?\.(dev-)?dependencies)\]/m.test(
        text
    );

/** A setup.py or setup.cfg that installs packages (`install_requires`, `extras_require` or `requires`). */
export const setupDeclaresDependencies = (text: string): boolean =>
    /\b(install_requires|extras_require|tests_require)\b/.test(text);

/** Any file that declares Python dependencies for pip, Pipenv, setuptools or a pyproject build. */
export function isDependencyFile(file: string, content: (file: string) => string): boolean {
    const base = path.posix.basename(file);
    if (base === "pyproject.toml") {
        return declaresDependencies(content(file));
    }
    if (base === "Pipfile" || base === "Pipfile.lock") {
        return true;
    }
    if (base === "setup.py" || base === "setup.cfg") {
        return setupDeclaresDependencies(content(file));
    }
    return isRequirementsStyleFile(file) && hasRequirementLines(content(file));
}

/**
 * Dependency files the CI audit does not cover and that are not exempt. A file is covered only when a
 * uv.lock sits in its directory and it is that project's pyproject.toml or a top-level
 * `requirements*.txt` or `requirements*.lock` (which the audit requires to be a uv export). Any other dependency file, even
 * beside a uv.lock (a Pipfile, a `requirements/` folder, a pip-compile lock), is reported. `files`
 * are repository-relative paths; `content` reads one of them.
 */
export function unlockedDependencyFiles(
    files: string[],
    content: (file: string) => string,
    exemptPaths: Set<string>
): string[] {
    const lockDirs = new Set(
        files.filter((f) => path.posix.basename(f) === "uv.lock").map((f) => path.posix.dirname(f))
    );
    return files.filter((file) => {
        if (exemptPaths.has(file) || !isDependencyFile(file, content)) {
            return false;
        }
        const base = path.posix.basename(file);
        const covered =
            lockDirs.has(path.posix.dirname(file)) &&
            (base === "pyproject.toml" || isUvExportName(file));
        return !covered;
    });
}

/**
 * Top-level `requirements*.txt` and `requirements*.lock` files in a uv.lock directory that do not start with the uv export
 * header. The audit regenerates and audits only uv exports, so a hand-written or header-less file
 * beside a lock would be installed unchecked; the audit job fails on it too.
 */
export function headerlessExports(files: string[], content: (file: string) => string): string[] {
    const lockDirs = new Set(
        files.filter((f) => path.posix.basename(f) === "uv.lock").map((f) => path.posix.dirname(f))
    );
    return files.filter(
        (file) =>
            isUvExportName(file) &&
            lockDirs.has(path.posix.dirname(file)) &&
            content(file)
                .replace(/^\uFEFF/, "")
                .split("\n")[0]
                .trim() !== UV_EXPORT_HEADER
    );
}

const files = trackedFiles();
const describeWithGit = files ? describe : describe.skip;

describe("Python dependency lock coverage (control)", () => {
    const sources: Record<string, string> = {
        "layers/new/pyproject.toml":
            '[project]\nname = "x"\ndependencies = [\n    "boto3==1.0.0",\n]\n',
        "layers/new/requirements.txt": "boto3==1.0.0\n",
        "layers/locked/pyproject.toml": '[project]\ndependencies = ["boto3==1.0.0"]\n',
        "layers/locked/uv.lock": "",
        "layers/empty/pyproject.toml": '[project]\nname = "x"\ndependencies = []\n',
        "notes/requirements.txt": "# install the CLI from the repository\n",
        "pipeline/poetry/pyproject.toml": '[tool.poetry.dependencies]\npython = "^3.12"\n',
    };
    const read = (f: string) => sources[f];

    test("a new pyproject and requirements file without a uv.lock are reported", () => {
        expect(unlockedDependencyFiles(Object.keys(sources), read, new Set())).toEqual([
            "layers/new/pyproject.toml",
            "layers/new/requirements.txt",
            "pipeline/poetry/pyproject.toml",
        ]);
    });

    test("other dependency file shapes are reported, beside a uv.lock too", () => {
        const shapes: Record<string, string> = {
            "a/Pipfile": "[packages]\nboto3 = '*'\n",
            "b/setup.py": "setup(name='x', install_requires=['boto3'])\n",
            "b2/setup.py": "setup(name='x')\n",
            "c/requirements/base.txt": "boto3==1.0.0\n",
            "d/requirements.in": "boto3\n",
            "e/dev-requirements.txt": "pytest==9.0.0\n",
            "f/requirements.lock": "boto3==1.0.0 \\\n    --hash=sha256:00\n",
            "g/requirements.lambda.lock": "boto3==1.0.0\n",
            "h/constraints.txt": "boto3==1.0.0\n",
            "i/pyproject.toml": '[project]\nname = "x"\ndynamic = ["version", "dependencies"]\n',
            "j/pyproject.toml": '[tool.poetry.dev-dependencies]\npytest = "*"\n',
            "k/pyproject.toml": '[tool.uv]\ndev-dependencies = [\n    "pytest",\n]\n',
            "l/MANIFEST.in": "include README.md\n",
            "m/uv.lock": "",
            "m/pyproject.toml": '[project]\ndependencies = ["boto3"]\n',
            "m/requirements.txt": UV_EXPORT_HEADER + "\nboto3==1.0.0\n",
            "m/Pipfile": "[packages]\n",
            "m/requirements/extra.txt": "boto3==1.0.0\n",
        };
        expect(
            unlockedDependencyFiles(Object.keys(shapes), (f) => shapes[f], new Set()).sort()
        ).toEqual(
            [
                "a/Pipfile",
                "b/setup.py",
                "c/requirements/base.txt",
                "d/requirements.in",
                "e/dev-requirements.txt",
                "f/requirements.lock",
                "g/requirements.lambda.lock",
                "h/constraints.txt",
                "i/pyproject.toml",
                "j/pyproject.toml",
                "k/pyproject.toml",
                "m/Pipfile",
                "m/requirements/extra.txt",
            ].sort()
        );
    });

    test("a requirements file in a locked directory must start with the uv export header", () => {
        const tree: Record<string, string> = {
            "layer/uv.lock": "",
            "layer/requirements.txt":
                UV_EXPORT_HEADER + "\n#    uv export -o requirements.txt\nidna==3.0\n",
            // A header-less, hand-edited export and a new hand-written file beside the lock.
            "layer/requirements-dev.txt": "idna==2.0\n",
            // A hashed export a Dockerfile installs: covered with the header, reported without it.
            "layer/requirements.lock":
                UV_EXPORT_HEADER + "\n#    uv export -o requirements.lock\nidna==3.0 \\\n    --hash=sha256:00\n",
            "layer/requirements-pip-compile.lock": "idna==3.0 \\\n    --hash=sha256:00\n",
            "layer/requirements-extra.txt": "jinja2==2.10\n",
            "unlocked/requirements.txt": "idna==2.0\n",
        };
        expect(headerlessExports(Object.keys(tree), (f) => tree[f]).sort()).toEqual([
            "layer/requirements-dev.txt",
            "layer/requirements-extra.txt",
            "layer/requirements-pip-compile.lock",
        ]);
    });

    test("an exemption removes a file from the report", () => {
        expect(
            unlockedDependencyFiles(
                Object.keys(sources),
                read,
                new Set([
                    "layers/new/pyproject.toml",
                    "layers/new/requirements.txt",
                    "pipeline/poetry/pyproject.toml",
                ])
            )
        ).toEqual([]);
    });
});

describeWithGit("Python dependency lock coverage", () => {
    const tracked = files ?? [];
    const exemptionFile = JSON.parse(read(EXEMPTIONS)) as { exemptions: Exemption[] };
    const exemptions = exemptionFile.exemptions;
    const trackedSet = new Set(tracked);
    const lockDirs = new Set(
        tracked
            .filter((f) => path.posix.basename(f) === "uv.lock")
            .map((f) => path.posix.dirname(f))
    );

    test("the repository has uv.lock projects for the audit job to find (control)", () => {
        expect(lockDirs.size).toBeGreaterThan(0);
        expect(lockDirs.has("backend")).toBe(true);
    });

    test("every Python dependency file has a sibling uv.lock or a reasoned exemption", () => {
        const missing = unlockedDependencyFiles(
            tracked,
            read,
            new Set(exemptions.map((e) => e.path))
        );
        if (missing.length > 0) {
            throw new Error(
                `Python dependency files the CI audit does not cover (no uv.lock beside them, or a file shape the audit does not read):\n  ${missing.join(
                    "\n  "
                )}\n` +
                    "The python-dependency-audit CI job audits only directories that have a uv.lock. " +
                    "Add a pyproject.toml, run `uv lock`, and commit uv.lock with its requirements.txt " +
                    "export (see the 'Python dependencies' section of the developer backend guide), or " +
                    `add an entry with a reason and the change that will add the lock to ${EXEMPTIONS}.`
            );
        }
    });

    test("every requirements*.txt and requirements*.lock beside a uv.lock is a uv export", () => {
        const headerless = headerlessExports(tracked, read);
        if (headerless.length > 0) {
            throw new Error(
                `requirements files beside a uv.lock without the uv export header:\n  ${headerless.join(
                    "\n  "
                )}\n` +
                    "The CI audit checks and audits only uv exports. Regenerate the file with the `uv export` " +
                    "command of the project's other exports, or remove it."
            );
        }
    });

    test("every exemption names a tracked dependency file, a reason and the change that adds its lock", () => {
        const problems: string[] = [];
        const seen = new Set<string>();
        exemptions.forEach((entry) => {
            const label = entry.path ?? JSON.stringify(entry);
            if (seen.has(entry.path)) {
                problems.push(`${label}: listed twice`);
            }
            seen.add(entry.path);
            if (!entry.reason?.trim()) {
                problems.push(`${label}: no reason`);
            }
            if (!entry.plannedIn?.trim()) {
                problems.push(`${label}: no plannedIn (the change that will add the lock)`);
            }
            if (!trackedSet.has(entry.path)) {
                problems.push(`${label}: not a tracked file any more; remove the exemption`);
            } else if (lockDirs.has(path.posix.dirname(entry.path))) {
                problems.push(`${label}: has a uv.lock beside it now; remove the exemption`);
            } else if (unlockedDependencyFiles([entry.path], read, new Set()).length === 0) {
                problems.push(`${label}: declares no Python dependencies; remove the exemption`);
            }
        });
        expect(problems).toEqual([]);
    });

    test("every uv.lock project requires the uv version the CI audit installs", () => {
        const ci = read(".github/workflows/ci.yml");
        const ciVersion =
            /uses: astral-sh\/setup-uv@[0-9a-f]{40}[^\n]*\n\s+with:\n\s+version: "([^"]+)"/.exec(
                ci
            )?.[1];
        expect(ciVersion).toMatch(/^\d+\.\d+\.\d+$/);
        lockDirs.forEach((dir) => {
            const pyproject = read(path.posix.join(dir, "pyproject.toml"));
            expect([dir, /^required-version\s*=\s*"==([^"]+)"/m.exec(pyproject)?.[1]]).toEqual([
                dir,
                ciVersion,
            ]);
        });
    });
});

describe("Python audit allowlist", () => {
    const allowlist = JSON.parse(read(ALLOWLIST)) as { entries: AllowlistEntry[] };
    const today = new Date().toISOString().slice(0, 10);

    test("the allowlist is an object with an entries list", () => {
        expect(Array.isArray(allowlist.entries)).toBe(true);
    });

    test("every entry has an id, a package, a reason and a review date that has not passed", () => {
        const problems: string[] = [];
        allowlist.entries.forEach((entry, index) => {
            const label = `entry ${index} (${entry.id})`;
            (["id", "package", "reason", "reviewBy"] as const).forEach((key) => {
                if (typeof entry[key] !== "string" || entry[key].trim() === "") {
                    problems.push(`${label}: no ${key}`);
                }
            });
            if (typeof entry.reviewBy === "string") {
                if (
                    !/^\d{4}-\d{2}-\d{2}$/.test(entry.reviewBy) ||
                    isNaN(Date.parse(entry.reviewBy))
                ) {
                    problems.push(`${label}: reviewBy is not an ISO date`);
                } else if (entry.reviewBy < today) {
                    problems.push(
                        `${label}: reviewBy ${entry.reviewBy} has passed; fix the package or review and extend the entry`
                    );
                }
            }
        });
        expect(problems).toEqual([]);
    });
});
