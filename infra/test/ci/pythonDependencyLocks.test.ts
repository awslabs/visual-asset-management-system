/** Tracked files, relative to the VAMS root; undefined when git is unavailable (a source archive). */
function trackedFiles(): string[] | undefined {
    try {
        return execFileSync("git", ["ls-files", "-z"], {
            cwd: REPO_ROOT,
            encoding: "utf8",
            maxBuffer: 64 * 1024 * 1024,
            stdio: ["ignore", "pipe", "ignore"],
        })
            .split("\0")
            .filter((p) => p !== "");
    } catch {
        return undefined;
    }
}

/** The export header every uv-exported requirements file starts with. */
export const UV_EXPORT_HEADER = "# This file was autogenerated by uv via the following command:";

/**
 * A top-level `requirements*.txt` or `requirements*.lock`: the only dependency files a locked directory may
 * hold beside its pyproject. A `.lock` is the hashed export a container Dockerfile installs with
 * `pip install --require-hashes`; it must carry the uv export header like any other export.
 */
const isUvExportName = (file: string): boolean =>
    /^requirements[^/]*\.(txt|lock)$/.test(path.posix.basename(file));

/**
 * A pip requirements-style file: any `.txt`, `.in` or `.lock` whose name contains `requirements`
 * (`requirements-dev.txt`, `dev-requirements.txt`, a pip-compile `requirements.lock`; beside a uv.lock only
 * a uv export is covered), a
 * `constraints*.txt`, any `.txt` or `.in` inside a `requirements/` folder, or any other `.in` file
 * except setuptools' `MANIFEST.in`. `uv.lock` is not one.
 */
export const isRequirementsStyleFile = (file: string): boolean => {
    const base = path.posix.basename(file);
    const dir = path.posix.basename(path.posix.dirname(file));
    return (
        /requirements[^/]*\.(txt|in|lock)$/i.test(base) ||
        /^constraints[^/]*\.txt$/i.test(base) ||
        (dir === "requirements" && /\.(txt|in)$/i.test(base)) ||
        (/\.in$/i.test(base) && base !== "MANIFEST.in")
    );
};

/** A requirements file with at least one line that is not blank or a comment. */
export const hasRequirementLines = (text: string): boolean =>
    text.split("\n").some((line) => line.trim() !== "" && !line.trim().startsWith("#"));

/**
 * A pyproject.toml that declares dependencies: a non-empty `[project] dependencies` list, dependencies
 * declared `dynamic`, a `[dependency-groups]` table, optional dependencies, Poetry dependency tables
 * (including the old `dev-dependencies`), or uv's legacy `dev-dependencies` list.
 */
export const declaresDependencies = (text: string): boolean =>
    /^\s*(dev-)?dependencies\s*=\s*\[\s*(#[^\n]*\n\s*)*["']/m.test(text) ||
    /^\s*dynamic\s*=\s*\[[^\]]*["'](dependencies|optional-dependencies)["']/m.test(text) ||
    /^\[(dependency-groups|project\.optional-dependencies|tool\.poetry(\.group\.[^\]]+)?\.(dev-)?dependencies)\]/m.test(
        text
    );

/** A setup.py or setup.cfg that installs packages (`install_requires`, `extras_require` or `requires`). */
export const setupDeclaresDependencies = (text: string): boolean =>
    /\b(install_requires|extras_require|tests_require)\b/.test(text);

/** Any file that declares Python dependencies for pip, Pipenv, setuptools or a pyproject build. */
export function isDependencyFile(file: string, content: (file: string) => string): boolean {
    const base = path.posix.basename(file);
    if (base === "pyproject.toml") {
        return declaresDependencies(content(file));
    }
    if (base === "Pipfile" || base === "Pipfile.lock") {
        return true;
    }
    if (base === "setup.py" || base === "setup.cfg") {
        return setupDeclaresDependencies(content(file));
    }
    return isRequirementsStyleFile(file) && hasRequirementLines(content(file));
}

/**
 * Dependency files the CI audit does not cover and that are not exempt. A file is covered only when a
 * uv.lock sits in its directory and it is that project's pyproject.toml or a top-level
 * `requirements*.txt` or `requirements*.lock` (which the audit requires to be a uv export). Any other dependency file, even
 * beside a uv.lock (a Pipfile, a `requirements/` folder, a pip-compile lock), is reported. `files`
 * are repository-relative paths; `content` reads one of them.
 */
export function unlockedDependencyFiles(
    files: string[],
    content: (file: string) => string,
    exemptPaths: Set<string>,
    rangedInputs: Set<string> = new Set()
): string[] {
    const lockDirs = new Set(
        files.filter((f) => path.posix.basename(f) === "uv.lock").map((f) => path.posix.dirname(f))
    );
    return files.filter((file) => {
        if (exemptPaths.has(file) || !isDependencyFile(file, content)) {
            return false;
        }
        const base = path.posix.basename(file);
        const covered =
            lockDirs.has(path.posix.dirname(file)) &&
            (base === "pyproject.toml" || isUvExportName(file) || rangedInputs.has(file));
        return !covered;
    });
}

/**
 * Top-level `requirements*.txt` and `requirements*.lock` files in a uv.lock directory that do not start with the uv export
 * header. The audit regenerates and audits only uv exports, so a hand-written or header-less file
 * beside a lock would be installed unchecked; the audit job fails on it too.
 */
export function headerlessExports(
    files: string[],
    content: (file: string) => string,
    rangedInputs: Set<string> = new Set()
): string[] {
    const lockDirs = new Set(
        files.filter((f) => path.posix.basename(f) === "uv.lock").map((f) => path.posix.dirname(f))
    );
    return files.filter(
        (file) =>
            isUvExportName(file) &&
            !rangedInputs.has(file) &&
            lockDirs.has(path.posix.dirname(file)) &&
            content(file)
                .replace(/^\uFEFF/, "")
                .split("\n")[0]
                .trim() !== UV_EXPORT_HEADER
    );
}

/**
 * Runs the audit script's own `check_ranged_inputs` (the CI job runs the same function) on a tree: the
 * `rangedInputs` of `.github/python-lock-exemptions.json` must have a reason, sit beside a uv.lock that
 * locks every package they name, and be installed by nothing. Returns the problems, or "" when valid.
 */
function rangedInputProblems(root: string, tracked: string[]): string {
    const code = [
        "import json, os, sys",
        `sys.path.insert(0, ${JSON.stringify(path.join(REPO_ROOT, ".github", "scripts"))})`,
        "import python_dependency_audit as m",
        "root, tracked = sys.argv[1], json.load(sys.stdin)",
        "lock_dirs = {os.path.dirname(p) or '.' for p in tracked if os.path.basename(p) == 'uv.lock'}",
        "try:",
        "    m.check_ranged_inputs(root, tracked, lock_dirs)",
        "except m.AuditError as exc:",
        "    print(exc)",
    ].join("\n");
    return execFileSync("python3", ["-c", code, root], {
        encoding: "utf8",
        input: JSON.stringify(tracked),
    }).trim();
}

/**
 * Runs the audit script's own `audit()` (what the CI job runs) on a tree, with `uv`, git and pip-audit
 * replaced: `findings` maps a project directory to the [package, version, [advisory ids]] pip-audit
 * reports for its committed export. The allowlist, its validation and its matching are the script's.
 * Returns the exit code and everything the run printed.
 */
function auditRun(
    root: string,
    tracked: string[],
    findings: Record<string, [string, string, string[]][]>
): { rc: number; out: string } {
    const code = [
        "import contextlib, io, json, os, sys, types",
        `sys.path.insert(0, ${JSON.stringify(path.join(REPO_ROOT, ".github", "scripts"))})`,
        "import python_dependency_audit as m",
        "root, spec = os.path.abspath(sys.argv[1]), json.load(sys.stdin)",
        "def tracked_files(d):",
        "    rel = os.path.relpath(os.path.abspath(d), root)",
        "    if rel == '.':",
        "        return spec['tracked']",
        "    return [p[len(rel) + 1:] for p in spec['tracked'] if p.startswith(rel + '/')]",
        "def audit_export(_root, rel, _pip_audit):",
        "    if os.path.isabs(rel):",
        "        return []",
        "    return [(p, v, ids) for p, v, ids in spec['findings'].get(os.path.dirname(rel), [])]",
        "m.tracked_files = tracked_files",
        "m.audit_export = audit_export",
        "m.run = lambda command, cwd, check=True: types.SimpleNamespace(returncode=0, stdout='', stderr='')",
        "m.tempfile.mkdtemp = lambda **kwargs: os.path.join(root, 'pip-audit-cache')",
        "sys.argv = ['audit', '--root', root, '--today', '2026-11-22']",
        "out = io.StringIO()",
        "with contextlib.redirect_stdout(out):",
        "    rc = m.main()",
        "print(json.dumps({'rc': rc, 'out': out.getvalue()}))",
    ].join("\n");
    const env: NodeJS.ProcessEnv = { ...process.env, PIP_AUDIT_VERSION: "2.10.1" };
    delete env.GITHUB_STEP_SUMMARY;
    return JSON.parse(
        execFileSync("python3", ["-c", code, root], {
            encoding: "utf8",
            env,
            input: JSON.stringify({ tracked, findings }),
        })
    );
}

/** A small tree in a temp directory; `files` maps repository paths to content. */
function withTree<T>(
    files: Record<string, string>,
    body: (root: string, tracked: string[]) => T
): T {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "ranged-inputs-"));
    try {
        Object.entries(files).forEach(([rel, text]) => {
            fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
            fs.writeFileSync(path.join(root, rel), text);
        });
        return body(root, Object.keys(files));
    } finally {
        fs.rmSync(root, { recursive: true, force: true });
    }
}

