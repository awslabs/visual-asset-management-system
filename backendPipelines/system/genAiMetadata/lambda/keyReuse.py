"""Which metadata key each analysed field lands in on a re-run, and which values the run may overwrite.

The analysis model fills a fixed list of fields (title, description, keywords, ...). Each field has a default
key in the pipeline's own namespace (``genai_title`` on a file, ``genai_asset_title`` on an asset). With key
reuse on, a field lands in a key the entity already carries instead, when the template's ``fieldMapping`` names
it: a file with a ``Material`` key receives the materials there rather than in a new ``genai_materials`` beside
it. The model never names a key: a target key is either a field's default key or a key the entity already
holds, matched by ``normalize_key``.

The merge rule protects what people wrote. Keys under ``genai_`` (and a legacy alias such as the asset's
``autoGeneratedKeywords``) are the pipeline's own and are always written. Any other key is written only when
the pipeline wrote its current value: the run records ``{key: sha256(value)}`` for every such key it writes
(the file's ``genai_written`` attribute, the asset's ``genai_asset_written`` metadata) and a later run writes
the key again only while the stored value still has that digest. A value a person edited is never overwritten:
the field lands in its default key instead and the skip is listed as a conflict. Beside the digest record a file
carries the targets record (``genai_targets``, ``{field: key}``): each field the run wrote outside its default key
and the key it went to, so a reader of the file's analysis (the asset summary) finds a field whose default key the
run cleared.

A key that is not the pipeline's own is written only once its type is known, whether it is empty or holds a
value an earlier run wrote. The metadata service answers a read with every field of the database's metadata
schemas, empty ones included, so an empty key is usually a schema field, and writing a string into a schema
field of another type (a controlled list, a number) makes the service refuse the whole metadata file. A key an
earlier run filled from the schema is just as typed, and the pipeline's write-back (as ``SYSTEM_USER``) is not
checked against the schema, so a wrong type or an unlisted value would be stored. ``schema_fields`` is where the
schema's field types plug in: ``None`` (not supplied) holds every such key back, leaving it as it is (the run
cannot tell a text key from a controlled list: the input carries values only, the digest record only their
hashes); a mapping of key to ``{"type", "controlledList"}`` writes a key it names when its type takes the value
(a text type keeps it, a controlled list takes the entry it names, in the list's spelling; any other type is
refused), and writes a key it does not name with the field's own type.

A pipeline-owned key the run no longer produces is cleared (written as an empty value), as is the default key
of a field that now lands elsewhere. A person-named key an earlier run wrote is cleared when its schema type
refuses this run's value, which then lands in the field's default key: it is written empty with the schema
type and leaves the digest record. Otherwise a person-named key is never cleared: not when a person owns it,
and not when the run does not produce its field or does not know its type.
"""

import hashlib
import json
import re
import unicodedata
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

TYPE_STRING = "string"
TYPE_MULTILINE_STRING = "multiline_string"
TYPE_CONTROLLED_LIST = "inline_controlled_list"
TEXT_TYPES = (TYPE_STRING, TYPE_MULTILINE_STRING)

# The fields a template's fieldMapping may name: the analysis model's result fields.
MAPPABLE_FIELDS = ("title", "description", "keywords", "category", "subcategory", "style", "materials", "colors",
                   "primaryColor", "objects", "orientation", "sizeEstimate", "textSummary")
# The shipped mapping: the names a person most often gives these fields. Names match after normalize_key, which
# also folds a plural, so "material" matches "Materials" and "MATERIAL".
FIELD_MAPPING_DEFAULT = {
    "title": ["title"],
    "description": ["description"],
    "keywords": ["keywords", "tags"],
    "category": ["category"],
    "materials": ["material"],
    "colors": ["color", "colour"],
}
FIELD_MAPPING_MAX_NAMES = 20
FIELD_MAPPING_MAX_NAME_CHARS = 128

# Keys no field ever lands in: this pipeline's own namespaces (their keys are the defaults, never matched) and
# the indexer's location key.
PIPELINE_KEY_PREFIXES = ("genai_", "ext_", "sys_")
RESERVED_KEYS = ("location",)
# Prefixes normalize_key strips before matching (the pipeline namespaces and the retired 2.6 attribute prefix).
MATCH_STRIPPED_PREFIXES = ("genai_", "ext_", "ab_")

# The digest records: a file attribute and an asset metadata key, both JSON objects of key -> sha256 hex.
FILE_DIGEST_KEY = "genai_written"
ASSET_DIGEST_KEY = "genai_asset_written"
# The file attribute naming, per field, the key the last run wrote that field to when it is not the field's default
# key (a JSON object of field -> key). A reader of the file's analysis, such as the asset summary, reads a field
# there when the field's default key is empty.
FILE_TARGETS_KEY = "genai_targets"

# The retired 2.6 labeling pipeline's asset keywords key. On an asset that carries it, it is the asset's
# keywords key and is treated as the pipeline's own.
LEGACY_ASSET_KEYWORDS_KEY = "autoGeneratedKeywords"

CONFLICT_EDITED = "edited"
CONFLICT_TYPE_UNKNOWN = "typeUnknown"
CONFLICT_TYPE_UNSUPPORTED = "typeUnsupported"
CONFLICT_NOT_IN_LIST = "notInControlledList"

_CAMEL_LOWER_UPPER = re.compile(r"([a-z0-9])([A-Z])")
_CAMEL_UPPER_RUN = re.compile(r"([A-Z]+)([A-Z][a-z])")
_NON_ALNUM = re.compile(r"[^a-z0-9]+")


@dataclass(frozen=True)
class FieldSpec:
    """One analysed field: its result name, its default key and the value type that key is written with."""
    name: str
    default_key: str
    value_type: str


@dataclass
class EntityPlan:
    """What one entity (a file or the asset) receives. ``rows`` are the metadata rows in field order, a cleared
    key as an empty value; ``targets`` maps each field that produced a value to the key it landed in;
    ``conflicts`` lists the keys the run left alone; ``cleared`` the keys it emptied; ``digests`` is the
    entity's digest record after the run and ``digests_changed`` whether it differs from the stored one."""
    rows: List[dict] = field(default_factory=list)
    targets: Dict[str, str] = field(default_factory=dict)
    conflicts: List[dict] = field(default_factory=list)
    cleared: List[str] = field(default_factory=list)
    digests: Dict[str, str] = field(default_factory=dict)
    digests_changed: bool = False


def _fold_plural(token: str) -> str:
    if len(token) > 4 and token.endswith("ies"):
        return token[:-3] + "y"
    if len(token) > 3 and token.endswith("s") and not token.endswith("ss"):
        return token[:-1]
    return token


def normalize_key(key) -> str:
    """The form two key names are compared in (stored keys keep their spelling): NFKC, camelCase split,
    lower case, every run outside ``[a-z0-9]`` one underscore, trimmed, one pipeline or legacy prefix stripped,
    and the last word's plural folded ("primaryColors" -> "primary_color", "AB_Materials" -> "material")."""
    text = unicodedata.normalize("NFKC", str(key or ""))
    text = _CAMEL_UPPER_RUN.sub(r"\1_\2", text)
    text = _CAMEL_LOWER_UPPER.sub(r"\1_\2", text)
    text = _NON_ALNUM.sub("_", text.lower()).strip("_")
    for prefix in MATCH_STRIPPED_PREFIXES:
        if text.startswith(prefix) and len(text) > len(prefix):
            text = text[len(prefix):]
            break
    if not text:
        return ""
    words = text.split("_")
    words[-1] = _fold_plural(words[-1])
    return "_".join(words)


def value_digest(value) -> str:
    return hashlib.sha256(str(value).encode("utf-8")).hexdigest()


def _blank(value) -> bool:
    return value is None or not str(value).strip()


def parse_digest_record(raw) -> Dict[str, str]:
    """A stored digest record (a JSON object string or an object) as ``{key: digest}``; ``{}`` when absent or
    unreadable, which makes every non-pipeline key a person's."""
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except ValueError:
            return {}
    if not isinstance(raw, dict):
        return {}
    return {str(key): str(value) for key, value in raw.items() if isinstance(value, str) and value}


def encode_digest_record(record: Dict[str, str]) -> str:
    return json.dumps(dict(sorted(record.items())), separators=(",", ":"))


def normalize_field_mapping(raw) -> Tuple[Dict[str, List[str]], List[str]]:
    """``(mapping, warnings)`` from the template's ``fieldMapping``: absent (None) is FIELD_MAPPING_DEFAULT; an
    object keeps the fields in MAPPABLE_FIELDS with their string names (at most FIELD_MAPPING_MAX_NAMES each, a
    name at most FIELD_MAPPING_MAX_NAME_CHARS characters); anything else is dropped with a warning."""
    if raw is None:
        return {name: list(names) for name, names in FIELD_MAPPING_DEFAULT.items()}, []
    if not isinstance(raw, dict):
        return {name: list(names) for name, names in FIELD_MAPPING_DEFAULT.items()}, [
            "fieldMapping is not an object; the default mapping was used"]
    mapping: Dict[str, List[str]] = {}
    warnings: List[str] = []
    for name, names in raw.items():
        if name not in MAPPABLE_FIELDS:
            warnings.append(f"fieldMapping names an unknown field {str(name)[:64]!r}; it was ignored")
            continue
        if isinstance(names, str):
            names = [names]
        if not isinstance(names, list):
            warnings.append(f"fieldMapping.{name} is not a list of names; it was ignored")
            continue
        kept = [str(item) for item in names
                if isinstance(item, str) and item.strip() and len(item) <= FIELD_MAPPING_MAX_NAME_CHARS]
        if len(kept) != len(names):
            warnings.append(f"fieldMapping.{name}: a name that is blank, not text or over "
                            f"{FIELD_MAPPING_MAX_NAME_CHARS} characters was ignored")
        if len(kept) > FIELD_MAPPING_MAX_NAMES:
            warnings.append(f"fieldMapping.{name}: only the first {FIELD_MAPPING_MAX_NAMES} names are used")
            kept = kept[:FIELD_MAPPING_MAX_NAMES]
        mapping[name] = kept
    return mapping, warnings


def is_reusable_key(key) -> bool:
    """Whether a key the entity carries may receive a field: not this pipeline's own namespace, not the
    location key, not a digest record or legacy alias, not blank."""
    text = str(key or "")
    lowered = text.strip().lower()
    if not lowered or lowered.startswith(PIPELINE_KEY_PREFIXES) or lowered in RESERVED_KEYS:
        return False
    return text not in (FILE_DIGEST_KEY, ASSET_DIGEST_KEY, FILE_TARGETS_KEY, LEGACY_ASSET_KEYWORDS_KEY)


def find_existing_key(field_name: str, existing: Dict[str, object], mapping: Dict[str, List[str]],
                      taken: Sequence[str] = ()) -> Optional[str]:
    """The key of ``existing`` that ``field_name`` reuses: the first mapping name, in the mapping's order, that a
    reusable key normalizes to; among several such keys the first in sorted order. ``taken`` keys (already chosen
    by an earlier field) are skipped, so two fields never share one key."""
    candidates = sorted(key for key in (existing or {}) if is_reusable_key(key) and key not in taken)
    normalized = {key: normalize_key(key) for key in candidates}
    for name in mapping.get(field_name) or []:
        wanted = normalize_key(name)
        if not wanted:
            continue
        for key in candidates:
            if normalized[key] == wanted:
                return key
    return None


def _fit_schema_value(value: str, schema_field: dict):
    """``(value, value_type, conflict_reason)`` for a value written into a schema-typed key: a text type keeps
    the value; a controlled list takes the list entry the value (or its first ", " item) names, in the list's
    spelling; any other type is refused."""
    value_type = str(schema_field.get("type") or TYPE_STRING).lower()
    if value_type in TEXT_TYPES:
        return value, value_type, None
    if value_type == TYPE_CONTROLLED_LIST:
        options = [str(option) for option in schema_field.get("controlledList") or []]
        by_lower = {option.lower(): option for option in options}
        for candidate in (value, value.split(",")[0]):
            match = by_lower.get(candidate.strip().lower())
            if match is not None:
                return match, value_type, None
        return None, value_type, CONFLICT_NOT_IN_LIST
    return None, value_type, CONFLICT_TYPE_UNSUPPORTED


def plan_entity(fields: Sequence[FieldSpec], values: Dict[str, Optional[str]], existing: Dict[str, object],
                mapping: Dict[str, List[str]], stored_digests: Dict[str, str], *, reuse: bool = True,
                aliases: Optional[Dict[str, str]] = None,
                schema_fields: Optional[Dict[str, dict]] = None) -> EntityPlan:
    """The rows one entity receives for ``values`` (field name -> rendered value, ``None`` or blank for a field
    the run did not produce).

    With ``reuse`` off this is the pipeline's plain output: one row per produced field at its default key,
    nothing cleared, no digest kept. With it on, each field's target is, in order: its ``aliases`` key when the
    entity carries it (pipeline-owned); else the key ``find_existing_key`` picks when the merge rule lets the run
    write it; else its default key. ``schema_fields`` (key -> ``{"type", "controlledList"}``) types each
    person-named key the run may write, an empty one or one whose value an earlier run wrote; ``None`` means the
    types are unknown and every such key is held back."""
    existing = existing or {}
    aliases = aliases or {}
    plan = EntityPlan(digests=dict(stored_digests or {}))
    taken: List[str] = []

    def row(key, value, value_type):
        plan.rows.append({"metadataKey": key, "metadataValue": value, "metadataValueType": value_type})

    for spec in fields:
        value = values.get(spec.name)
        value = None if _blank(value) else str(value)
        if not reuse:
            if value is not None:
                row(spec.default_key, value, spec.value_type)
                plan.targets[spec.name] = spec.default_key
            continue
        target, owned, value_type, written = spec.default_key, True, spec.value_type, value
        alias = aliases.get(spec.name)
        candidate = None
        if alias and alias in existing:
            target = alias
        else:
            candidate = find_existing_key(spec.name, existing, mapping, taken)
        stale = None
        if candidate is not None:
            taken.append(candidate)
            current = existing.get(candidate)
            # Written by an earlier run: the stored value still has the digest that run recorded.
            ours = not _blank(current) and plan.digests.get(candidate) == value_digest(current)
            reason, fitted, fitted_type = None, value, spec.value_type
            if not _blank(current) and not ours:
                reason = CONFLICT_EDITED
            elif schema_fields is None:
                reason = CONFLICT_TYPE_UNKNOWN
            elif candidate in schema_fields and value is not None:
                fitted, fitted_type, reason = _fit_schema_value(value, schema_fields[candidate])
            if reason is None:
                target, owned, written, value_type = candidate, False, fitted, fitted_type
            elif value is not None:
                plan.conflicts.append({"field": spec.name, "key": candidate, "reason": reason})
                if ours and reason in (CONFLICT_NOT_IN_LIST, CONFLICT_TYPE_UNSUPPORTED):
                    # The schema refuses this run's value, which lands in the default key: the earlier value
                    # would stand beside it as if it were current.
                    stale = (candidate, fitted_type)
        if written is not None:
            row(target, written, value_type)
            plan.targets[spec.name] = target
            if not owned:
                plan.digests[target] = value_digest(written)
        elif owned and not _blank(existing.get(target)):
            row(target, "", value_type)
            plan.cleared.append(target)
        if stale is not None:
            row(stale[0], "", stale[1])
            plan.cleared.append(stale[0])
            plan.digests.pop(stale[0], None)
        # The default key of a field that lands elsewhere is never produced again.
        if target != spec.default_key and not _blank(existing.get(spec.default_key)):
            row(spec.default_key, "", spec.value_type)
            plan.cleared.append(spec.default_key)
    plan.digests_changed = plan.digests != dict(stored_digests or {})
    return plan


def moved_targets(fields: Sequence[FieldSpec], plan: EntityPlan) -> Dict[str, str]:
    """``{field: key}`` for each field of ``plan`` that landed outside its default key: the targets record
    (FILE_TARGETS_KEY) a reader of the entity's analysis follows when a field's default key is empty."""
    defaults = {spec.name: spec.default_key for spec in fields}
    return {name: key for name, key in sorted(plan.targets.items()) if key != defaults.get(name)}


def parse_targets_record(raw) -> Dict[str, str]:
    """A stored targets record (a JSON object string or an object) as ``{field: key}`` for the fields in
    MAPPABLE_FIELDS; ``{}`` when absent or unreadable."""
    return {name: key for name, key in parse_digest_record(raw).items() if name in MAPPABLE_FIELDS}


def file_extension(file_key) -> Optional[str]:
    """The dotted, lower-case extension of a file key's base name, the form a schema's
    ``fileKeyTypeRestriction`` lists; ``None`` for a name without one and for a folder key. The metadata
    service reads it the same way (``metadataSchemaValidation.extract_file_extension``)."""
    text = str(file_key or "")
    if not text or text.endswith("/"):
        return None
    name = text.rsplit("/", 1)[-1]
    if "." not in name:
        return None
    return "." + name.rsplit(".", 1)[-1].lower()


def schema_entry(metadata_body, database_id) -> Optional[dict]:
    """The input envelope's ``metadataSchemas`` entry for one database (its own schemas and the GLOBAL ones
    folded together), or ``None`` when the envelope carries none for it: the run did not ask for the section, or
    the launching identity may not read that database's schemas."""
    entries = (metadata_body or {}).get("metadataSchemas") if isinstance(metadata_body, dict) else None
    if not isinstance(entries, list):
        return None
    for entry in entries:
        if isinstance(entry, dict) and entry.get("databaseId") == database_id:
            return entry
    return None


def schema_field_types(entry_fields, file_key=None) -> Dict[str, dict]:
    """``{key: {"type", "controlledList"}}`` from one entity type's field list of a schema entry.

    Asset metadata (``file_key`` None) takes every field. A file takes, per field, the entry whose
    ``fileKeyTypeRestriction`` lists its extension, else the entry with an empty list (every file); a file
    without an extension takes only the unrestricted entries, which is what the metadata service validates
    that file against."""
    by_name: Dict[str, List[dict]] = {}
    for item in entry_fields or []:
        if isinstance(item, dict) and str(item.get("metadataFieldKeyName") or "").strip():
            by_name.setdefault(str(item["metadataFieldKeyName"]), []).append(item)
    extension = file_extension(file_key) if file_key is not None else None
    types: Dict[str, dict] = {}
    for name, items in by_name.items():
        chosen = items[0]
        if file_key is not None:
            restricted = [item for item in items
                          if extension and extension in [str(ext).lower() for ext in
                                                         item.get("fileKeyTypeRestriction") or []]]
            unrestricted = [item for item in items if not item.get("fileKeyTypeRestriction")]
            if not (restricted or unrestricted):
                continue
            chosen = (restricted or unrestricted)[0]
        types[name] = {"type": str(chosen.get("metadataFieldValueType") or TYPE_STRING),
                       "controlledList": [str(value) for value in chosen.get("controlledListKeys") or []]}
    return types


def controlled_targets(fields: Sequence[FieldSpec], existing: Dict[str, object], mapping: Dict[str, List[str]],
                       stored_digests: Dict[str, str], schema_fields: Optional[Dict[str, dict]], *,
                       aliases: Optional[Dict[str, str]] = None) -> Dict[str, List[str]]:
    """``{field: controlled list}`` for each field whose value would land in a schema key of the controlled-list
    type, so the request can offer the list's values up front. The targets are the ones
    ``plan_entity`` picks when every field produces a value and every schema key takes text; a field it would
    send to its default key, or to a key a person edited, is not constrained."""
    if not schema_fields:
        return {}
    as_text = {key: dict(spec, type=TYPE_STRING) for key, spec in schema_fields.items()}
    plan = plan_entity(fields, {spec.name: "value" for spec in fields}, existing, mapping, stored_digests,
                       aliases=aliases, schema_fields=as_text)
    constrained: Dict[str, List[str]] = {}
    for name, key in plan.targets.items():
        spec = schema_fields.get(key) or {}
        values = [value for value in spec.get("controlledList") or [] if str(value).strip()]
        if str(spec.get("type") or "").lower() == TYPE_CONTROLLED_LIST and values:
            constrained[name] = values
    return constrained


def previous_values(fields: Sequence[FieldSpec], existing: Dict[str, object],
                    aliases: Optional[Dict[str, str]] = None) -> List[Tuple[str, object]]:
    """``(field, value)`` of the entity's current pipeline-owned values, in field order: each field's alias key
    when the entity carries it, else its default key; blank values skipped. These are the pipeline's earlier
    result, which the next analysis sees so its wording stays stable between runs."""
    existing = existing or {}
    aliases = aliases or {}
    found = []
    for spec in fields:
        alias = aliases.get(spec.name)
        key = alias if alias and alias in existing else spec.default_key
        value = existing.get(key)
        if not _blank(value):
            found.append((spec.name, value))
    return found
