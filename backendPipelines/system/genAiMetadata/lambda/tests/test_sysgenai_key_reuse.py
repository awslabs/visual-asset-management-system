@pytest.mark.unit
class TestFieldMapping:
    def test_absent_is_the_shipped_default(self):
        mapping, warnings = kr.normalize_field_mapping(None)
        assert mapping == kr.FIELD_MAPPING_DEFAULT and warnings == []
        assert mapping is not kr.FIELD_MAPPING_DEFAULT

    def test_the_default_names_only_mappable_fields(self):
        assert set(kr.FIELD_MAPPING_DEFAULT) <= set(kr.MAPPABLE_FIELDS)

    def test_an_object_keeps_known_fields_and_warns_about_the_rest(self):
        mapping, warnings = kr.normalize_field_mapping({
            "title": ["Name", "", 3], "materials": "Werkstoff", "colors": {"x": 1}, "rating": ["Stars"],
            "keywords": [f"k{i}" for i in range(25)], "style": ["s" * 129],
        })
        assert mapping == {"title": ["Name"], "materials": ["Werkstoff"],
                           "keywords": [f"k{i}" for i in range(20)], "style": []}
        assert any("'rating'" in warning for warning in warnings)
        assert any("fieldMapping.colors" in warning for warning in warnings)
        assert any("fieldMapping.title" in warning for warning in warnings)
        assert any("first 20 names" in warning for warning in warnings)

    def test_a_non_object_is_the_default_with_a_warning(self):
        mapping, warnings = kr.normalize_field_mapping(["title"])
        assert mapping == kr.FIELD_MAPPING_DEFAULT and len(warnings) == 1


@pytest.mark.unit
class TestFindExistingKey:
    def test_a_mapping_name_matches_a_key_of_any_spelling(self):
        assert kr.find_existing_key("materials", {"MATERIALS": "x", "PART_NO": "1"}, MAPPING) == "MATERIALS"

    def test_the_pipeline_namespaces_and_reserved_keys_are_never_reused(self):
        existing = {"genai_material": "x", "ext_material": "y", "sys_material": "z", "AB_Material": "w"}
        # AB_ is not this pipeline's namespace: it is a person's key for the merge rule, and it matches.
        assert kr.find_existing_key("materials", existing, MAPPING) == "AB_Material"
        assert kr.find_existing_key("materials", {"genai_material": "x", "ext_material": "y"}, MAPPING) is None
        assert kr.find_existing_key("title", {"location": "x"}, {"title": ["location"]}) is None
        assert kr.find_existing_key("keywords", {"autoGeneratedKeywords": "x"},
                                    {"keywords": ["autoGeneratedKeywords"]}) is None

    def test_the_mapping_order_decides_and_then_the_sorted_key(self):
        mapping = {"colors": ["color", "colour"]}
        assert kr.find_existing_key("colors", {"Colour": "a", "color": "b"}, mapping) == "color"
        assert kr.find_existing_key("colors", {"Colour": "a", "COLOUR": "b"}, mapping) == "COLOUR"

    def test_a_key_taken_by_an_earlier_field_is_skipped(self):
        mapping = {"colors": ["color"], "primaryColor": ["color"]}
        assert kr.find_existing_key("primaryColor", {"Color": "x"}, mapping, taken=["Color"]) is None

    def test_an_unmapped_field_reuses_nothing(self):
        assert kr.find_existing_key("objects", {"Objects": "x"}, MAPPING) is None


@pytest.mark.unit
class TestPlanEntity:
    def test_reuse_off_is_the_plain_default_key_layer(self):
        existing = {"Material": "", "genai_text_summary": "old", "Title": "x"}
        plan = kr.plan_entity(FIELDS, VALUES, existing, MAPPING, {}, reuse=False)
        assert [row["metadataKey"] for row in plan.rows] == ["genai_title", "genai_description", "genai_materials"]
        assert plan.cleared == [] and plan.conflicts == [] and plan.digests_changed is False

    def test_nothing_to_reuse_is_the_default_layer(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"PART_NO": "1"}, MAPPING, {})
        assert _rows(plan) == {"genai_title": "Brass gear pump", "genai_description": "A pump.",
                               "genai_materials": "brass, steel"}
        assert plan.targets == {"title": "genai_title", "description": "genai_description",
                                "materials": "genai_materials"}

    def test_the_value_types_are_the_fields(self):
        plan = kr.plan_entity(FIELDS, VALUES, {}, MAPPING, {})
        assert {row["metadataKey"]: row["metadataValueType"] for row in plan.rows} == {
            "genai_title": "string", "genai_description": "multiline_string", "genai_materials": "string"}

    def test_an_edited_person_key_is_skipped_and_listed(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"Material": "iron"}, MAPPING, {"Material": kr.value_digest("bronze")})
        assert "Material" not in _rows(plan) and _rows(plan)["genai_materials"] == "brass, steel"
        assert plan.conflicts == [{"field": "materials", "key": "Material", "reason": "edited"}]

    def test_a_key_whose_value_the_pipeline_wrote_is_written_and_recorded(self):
        stored = {"Material": kr.value_digest("bronze"), "Other": "keep"}
        plan = kr.plan_entity(FIELDS, VALUES, {"Material": "bronze"}, MAPPING, stored, schema_fields=NO_SCHEMA_FIELDS)
        assert _rows(plan)["Material"] == "brass, steel" and "genai_materials" not in _rows(plan)
        assert plan.digests == {"Material": kr.value_digest("brass, steel"), "Other": "keep"}
        assert plan.digests_changed is True

    def test_an_empty_person_key_is_held_back_without_the_schema(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"Description": ""}, MAPPING, {})
        assert _rows(plan)["genai_description"] == "A pump." and "Description" not in _rows(plan)
        assert plan.conflicts == [{"field": "description", "key": "Description", "reason": "typeUnknown"}]

    def test_with_the_schema_an_empty_free_key_is_written(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"Description": ""}, MAPPING, {}, schema_fields={})
        assert _rows(plan)["Description"] == "A pump." and "genai_description" not in _rows(plan)
        assert plan.digests == {"Description": kr.value_digest("A pump.")}

    def test_with_the_schema_a_text_field_takes_the_schema_type(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"Description": ""}, MAPPING, {},
                              schema_fields={"Description": {"type": "string"}})
        row = next(row for row in plan.rows if row["metadataKey"] == "Description")
        assert row == {"metadataKey": "Description", "metadataValue": "A pump.", "metadataValueType": "string"}

    def test_with_the_schema_a_controlled_list_takes_the_entry_the_value_names(self):
        schema = {"Material": {"type": "inline_controlled_list", "controlledList": ["Steel", "Brass"]}}
        plan = kr.plan_entity(FIELDS, VALUES, {"Material": ""}, MAPPING, {}, schema_fields=schema)
        row = next(row for row in plan.rows if row["metadataKey"] == "Material")
        assert row == {"metadataKey": "Material", "metadataValue": "Brass",
                       "metadataValueType": "inline_controlled_list"}
        assert plan.digests == {"Material": kr.value_digest("Brass")}

    def test_with_the_schema_a_value_outside_the_controlled_list_lands_in_the_default_key(self):
        schema = {"Material": {"type": "inline_controlled_list", "controlledList": ["Wood"]}}
        plan = kr.plan_entity(FIELDS, VALUES, {"Material": ""}, MAPPING, {}, schema_fields=schema)
        assert "Material" not in _rows(plan) and _rows(plan)["genai_materials"] == "brass, steel"
        assert plan.conflicts == [{"field": "materials", "key": "Material", "reason": "notInControlledList"}]

    def test_with_the_schema_a_non_text_type_is_refused(self):
        schema = {"Title": {"type": "number"}}
        plan = kr.plan_entity(FIELDS, VALUES, {"Title": ""}, MAPPING, {}, schema_fields=schema)
        assert _rows(plan)["genai_title"] == "Brass gear pump"
        assert plan.conflicts == [{"field": "title", "key": "Title", "reason": "typeUnsupported"}]

    def test_a_pipeline_owned_key_no_longer_produced_is_cleared(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"genai_text_summary": "old summary"}, MAPPING, {})
        assert _rows(plan)["genai_text_summary"] == "" and plan.cleared == ["genai_text_summary"]

    def test_a_blank_pipeline_owned_key_is_not_cleared_again(self):
        plan = kr.plan_entity(FIELDS, VALUES, {"genai_text_summary": " "}, MAPPING, {})
        assert "genai_text_summary" not in _rows(plan) and plan.cleared == []

    def test_a_persons_key_is_never_cleared(self):
        mapping = dict(MAPPING, textSummary=["summary"])
        stored = {"Summary": kr.value_digest("ours")}
        plan = kr.plan_entity(FIELDS, VALUES, {"Summary": "ours"}, mapping, stored)
        assert "Summary" not in _rows(plan)

    def test_the_default_key_of_a_field_that_moved_is_cleared(self):
        existing = {"Material": "bronze", "genai_materials": "bronze"}
        plan = kr.plan_entity(FIELDS, VALUES, existing, MAPPING, {"Material": kr.value_digest("bronze")},
                              schema_fields=NO_SCHEMA_FIELDS)
        assert _rows(plan)["genai_materials"] == "" and "genai_materials" in plan.cleared

    def test_an_alias_the_entity_carries_is_the_pipelines_own(self):
        fields = (kr.FieldSpec("keywords", "genai_asset_keywords", "string"),)
        existing = {"autoGeneratedKeywords": "edited by hand", "genai_asset_keywords": "old"}
        plan = kr.plan_entity(fields, {"keywords": "pump, brass"}, existing, {"keywords": ["keywords"]}, {},
                              aliases={"keywords": "autoGeneratedKeywords"})
        assert _rows(plan) == {"autoGeneratedKeywords": "pump, brass", "genai_asset_keywords": ""}
        assert plan.digests == {} and plan.conflicts == []

    def test_an_alias_the_entity_lacks_is_ignored(self):
        fields = (kr.FieldSpec("keywords", "genai_asset_keywords", "string"),)
        plan = kr.plan_entity(fields, {"keywords": "pump"}, {}, {}, {}, aliases={"keywords": "autoGeneratedKeywords"})
        assert _rows(plan) == {"genai_asset_keywords": "pump"}

    def test_a_field_the_run_did_not_produce_lists_no_conflict(self):
        values = dict(VALUES, materials=None)
        plan = kr.plan_entity(FIELDS, values, {"Material": "iron"}, MAPPING, {})
        assert plan.conflicts == [] and "Material" not in _rows(plan)

    def test_two_fields_never_share_one_key(self):
        fields = (kr.FieldSpec("colors", "genai_colors", "string"),
                  kr.FieldSpec("primaryColor", "genai_primary_color", "string"))
        mapping = {"colors": ["color"], "primaryColor": ["color"]}
        stored = {"Color": kr.value_digest("red")}
        plan = kr.plan_entity(fields, {"colors": "gold, gray", "primaryColor": "gold"}, {"Color": "red"},
                              mapping, stored, schema_fields=NO_SCHEMA_FIELDS)
        assert _rows(plan) == {"Color": "gold, gray", "genai_primary_color": "gold"}

    def test_the_unchanged_record_is_reported_unchanged(self):
        stored = {"Material": kr.value_digest("brass, steel")}
        plan = kr.plan_entity(FIELDS, VALUES, {"Material": "brass, steel"}, MAPPING, stored,
                              schema_fields=NO_SCHEMA_FIELDS)
        assert _rows(plan)["Material"] == "brass, steel" and plan.digests_changed is False


SECOND_RUN_FIELDS = (
    kr.FieldSpec("description", "genai_description", "multiline_string"),
    kr.FieldSpec("materials", "genai_materials", "string"),
)
SECOND_RUN_SCHEMA = {
    "material": {"type": "inline_controlled_list", "controlledList": ["Steel", "Aluminium"]},
    "description": {"type": "string", "controlledList": []},
}


def _after(existing, plan):
    """The entity as the write-back leaves it: the plan's rows applied over what it carried."""
    state = dict(existing)
    state.update(_rows(plan))
    return state


def _first_run(schema=SECOND_RUN_SCHEMA):
    """A first run over a file whose schema fields are empty, and the entity and digest record it leaves."""
    existing = {"material": "", "description": ""}
    plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "steel, aluminium"},
                          existing, MAPPING, {}, schema_fields=schema)
    return _after(existing, plan), plan.digests


def _row(plan, key):
    return next(row for row in plan.rows if row["metadataKey"] == key)


@pytest.mark.unit
class TestSecondRun:
    """A person-named key the pipeline filled on an earlier run (it owns it by digest) is typed by the schema
    exactly like an empty one."""

    def test_the_first_run_fits_the_controlled_list(self):
        state, digests = _first_run()
        assert state == {"material": "Steel", "description": "A pump."}
        assert digests == {"material": kr.value_digest("Steel"), "description": kr.value_digest("A pump.")}

    def test_a_controlled_list_key_takes_the_lists_spelling_again(self):
        state, digests = _first_run()
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "steel, aluminium"},
                              state, MAPPING, digests, schema_fields=SECOND_RUN_SCHEMA)
        assert _row(plan, "material") == {"metadataKey": "material", "metadataValue": "Steel",
                                          "metadataValueType": "inline_controlled_list"}
        assert plan.conflicts == [] and plan.cleared == [] and plan.digests_changed is False

    def test_a_value_outside_the_list_lands_in_the_pipeline_key_and_the_earlier_value_is_cleared(self):
        state, digests = _first_run()
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "copper"},
                              state, MAPPING, digests, schema_fields=SECOND_RUN_SCHEMA)
        assert _row(plan, "genai_materials") == {"metadataKey": "genai_materials", "metadataValue": "copper",
                                                 "metadataValueType": "string"}
        assert _row(plan, "material") == {"metadataKey": "material", "metadataValue": "",
                                          "metadataValueType": "inline_controlled_list"}
        assert plan.conflicts == [{"field": "materials", "key": "material", "reason": "notInControlledList"}]
        assert plan.cleared == ["material"] and plan.targets["materials"] == "genai_materials"
        assert "material" not in plan.digests and plan.digests_changed is True
        # Emptied, the key is an empty schema key again: the next run fills it from the list when the value fits.
        third = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "aluminium"},
                               _after(state, plan), MAPPING, plan.digests, schema_fields=SECOND_RUN_SCHEMA)
        assert _rows(third)["material"] == "Aluminium" and _rows(third)["genai_materials"] == ""

    def test_a_text_key_keeps_the_value_in_the_schemas_type(self):
        state, digests = _first_run()
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A brass gear pump.", "materials": "steel"},
                              state, MAPPING, digests, schema_fields=SECOND_RUN_SCHEMA)
        # The schema says string; the field's own key would be multiline_string.
        assert _row(plan, "description") == {"metadataKey": "description", "metadataValue": "A brass gear pump.",
                                             "metadataValueType": "string"}
        assert plan.digests["description"] == kr.value_digest("A brass gear pump.") and plan.conflicts == []

    def test_a_key_whose_schema_type_no_longer_takes_text_is_cleared(self):
        state, digests = _first_run()
        schema = dict(SECOND_RUN_SCHEMA, description={"type": "number", "controlledList": []})
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "steel"},
                              state, MAPPING, digests, schema_fields=schema)
        assert _rows(plan)["genai_description"] == "A pump."
        assert _row(plan, "description") == {"metadataKey": "description", "metadataValue": "",
                                             "metadataValueType": "number"}
        assert plan.conflicts == [{"field": "description", "key": "description", "reason": "typeUnsupported"}]
        assert plan.cleared == ["description"] and "description" not in plan.digests

    def test_without_the_schema_a_key_an_earlier_run_wrote_is_held_back_and_kept(self):
        """The run cannot tell a text key from a controlled list without the schema, so it writes no row into
        the key; the earlier value and its digest stay, so a run with the schema takes the key over again."""
        state, digests = _first_run()
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A brass pump.", "materials": "steel, aluminium"},
                              state, MAPPING, digests)
        assert _rows(plan) == {"genai_description": "A brass pump.", "genai_materials": "steel, aluminium"}
        assert plan.conflicts == [{"field": "description", "key": "description", "reason": "typeUnknown"},
                                  {"field": "materials", "key": "material", "reason": "typeUnknown"}]
        assert plan.cleared == [] and plan.digests == digests and plan.digests_changed is False
        later = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A brass pump.", "materials": "steel"},
                               _after(state, plan), MAPPING, plan.digests, schema_fields=SECOND_RUN_SCHEMA)
        assert _rows(later) == {"description": "A brass pump.", "genai_description": "", "material": "Steel",
                                "genai_materials": ""}

    def test_a_field_the_run_did_not_produce_leaves_the_key_alone(self):
        state, digests = _first_run()
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": None},
                              state, MAPPING, digests, schema_fields=SECOND_RUN_SCHEMA)
        assert "material" not in _rows(plan) and plan.cleared == [] and plan.conflicts == []
        assert plan.digests["material"] == kr.value_digest("Steel")

    def test_the_tool_asks_for_the_list_and_the_merge_writes_its_entry(self):
        """controlled_targets (the values the tool offers) and plan_entity agree on the key a field lands in."""
        state, digests = _first_run()
        assert kr.controlled_targets(SECOND_RUN_FIELDS, state, MAPPING, digests, SECOND_RUN_SCHEMA) == {
            "materials": ["Steel", "Aluminium"]}
        plan = kr.plan_entity(SECOND_RUN_FIELDS, {"description": "A pump.", "materials": "aluminium"},
                              state, MAPPING, digests, schema_fields=SECOND_RUN_SCHEMA)
        assert plan.targets["materials"] == "material"
        assert _row(plan, "material")["metadataValue"] == "Aluminium"
        assert _row(plan, "material")["metadataValueType"] == "inline_controlled_list"
        assert kr.controlled_targets(SECOND_RUN_FIELDS, state, MAPPING, digests, None) == {}


@pytest.mark.unit
class TestDigestRecord:
    def test_round_trip(self):
        record = {"b": kr.value_digest("2"), "a": kr.value_digest("1")}
        encoded = kr.encode_digest_record(record)
        assert json.loads(encoded) == record and encoded.index('"a"') < encoded.index('"b"')
        assert kr.parse_digest_record(encoded) == record

    @pytest.mark.parametrize("raw", [None, "", "not json", "[1]", '{"a": 1}', 7])
    def test_an_unreadable_record_is_empty(self, raw):
        assert kr.parse_digest_record(raw) == {}

    def test_the_digest_is_sha256_of_the_text(self):
        assert kr.value_digest("brass") == hashlib.sha256("brass".encode("utf-8")).hexdigest()
        assert kr.value_digest("brass") != kr.value_digest("Brass")


