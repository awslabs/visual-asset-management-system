"""With reuseExistingKeys off, the analysis step's output is the output it produced before key reuse existed.

``golden/reuse_off_outputs.json`` holds, per scenario, the Converse request and the files the analysis step
wrote (the file's metadata and attributes, the asset's metadata when written), recorded from the analysis step
as it was before key reuse, the write target and the model settings were added. Each scenario's envelope
carries what key reuse acts on — earlier genai_* values (one the model no longer produces), person-named keys
the default fieldMapping matches, an empty such key, a digest record, and the retired pipeline's
autoGeneratedKeywords — so a reuse-off run that reused, cleared or quoted any of them would differ.

The timestamp is replaced by a marker and image bytes by their length before the comparison. The owner-requested
content-first instructions (the system prompt's CONTENT_FIRST_SYSTEM_TEXT, which also says every image is taken from
the file, the user message's CONTENT_FIRST_INSTRUCTION and the CONTEXT_LABEL before the asset text) and the
asset-text digest attribute (genai_context_digest) postdate the recording and are taken out, each by its exact text or
key; the closing line that announces the images (images_line, D117, with its screen rule) is put back to the recorded
wording by its exact text. The instruction now comes before that line; once it is taken out the order is the
recorded one. Any other change to
the request or the files still fails; nothing else is normalised."""

