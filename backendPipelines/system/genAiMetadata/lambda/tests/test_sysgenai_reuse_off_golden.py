def _seed(s3, scenario):
    manifest = {
        "schemaVersion": 1, "fileClass": scenario["fileClass"], "renderBranch": scenario["renderBranch"],
        "attributes": json.loads(json.dumps(scenario["attributes"])),
        "renderImages": [f"{AUX_PREFIX}renders/view{i}.png" for i in range(scenario["images"])],
        "textExcerpt": scenario["textExcerpt"], "facts": scenario["facts"], "warnings": [], "renderSkipped": None,
    }
    s3.put_json(AUX, MANIFEST_KEY, manifest)
    s3.put_json("abkt", CONFIG_KEY, dict(CONFIG, **scenario["config"]))
    file_record = {"fileKey": scenario["relativePath"], "metadata": scenario["fileMetadata"],
                   "attributes": scenario["fileAttributes"]}
    s3.put_json("abkt", METADATA_KEY, {
        "schemaVersion": 2,
        "assets": [{"databaseId": "dbM", "assetId": "xidM",
                    "assetData": {"assetName": "Gear Pump", "description": "A brass gear pump", "tags": ["pump"]},
                    "files": [{"fileKey": "/", "metadata": scenario["assetMetadata"]}, file_record]}],
        "databases": [{"databaseId": "dbM", "metadata": {"SITE": "Plant 7"}}],
    })
    for index, key in enumerate(manifest["renderImages"]):
        s3.objects[(AUX, key)] = b"\x89PNG\r\n\x1a\n" + bytes([index]) * 100


def _state(scenario):
    return {
        "jobName": "PipelineJob_golden", "externalSfnTaskToken": h.TASK_TOKEN,
        "inputS3AssetFilePath": "s3://abkt/xidM" + scenario["relativePath"],
        "outputS3AssetMetadataPath": f"s3://abkt/{META_PREFIX}", "outputS3AssetResultsPath": f"s3://abkt/{RESULTS_PREFIX}",
        "inputOutputS3AssetAuxiliaryFilesPath": f"s3://{AUX}/{AUX_PREFIX}",
        "inputMetadataS3Location": f"s3://abkt/{METADATA_KEY}", "inputConfigurationS3Location": f"s3://abkt/{CONFIG_KEY}",
        "assetId": "xidM", "databaseId": "dbM", "relativePath": scenario["relativePath"], "versionId": "v1",
        "fileClass": scenario["fileClass"], "fileExt": scenario["fileExt"], "renderBranch": scenario["renderBranch"],
        "analysisManifestS3Location": f"s3://{AUX}/{MANIFEST_KEY}", "vectorSearchEnabled": True,
    }


def _normalise_rows(body):
    for row in body.get("metadata") or []:
        if row.get("metadataKey") in ("genai_generated_at", "genai_asset_generated_at"):
            row["metadataValue"] = TIMESTAMP_MARKER
    return body


def _normalise_request(request):
    request = json.loads(json.dumps(request, default=lambda value: {"bytesLength": len(value)}))
    return request


def run_scenario(name):
    """The scenario's Converse request and output files, normalised for comparison."""
    scenario = SCENARIOS[name]
    s3 = h.FakeS3()
    _seed(s3, scenario)
    bedrock = h.FakeBedrock([h.converse_response(json.dumps(MODEL_REPLY))])
    mod = h.load_handler("generateMetadata")
    mod.s3_client = s3
    mod.bedrock_runtime = bedrock
    mod.time = MagicMock()
    mod.lambda_handler(_state(scenario), MagicMock())
    stem = scenario["relativePath"].lstrip("/")
    outputs = {}
    for label, key in (("metadata", META_PREFIX + stem + ".metadata.json"),
                       ("attributes", META_PREFIX + stem + ".attribute.json"),
                       ("assetMetadata", META_PREFIX + "asset.metadata.json")):
        outputs[label] = _normalise_rows(s3.json_at("abkt", key)) if ("abkt", key) in s3.objects else None
    assert len(bedrock.calls) == 1, name
    return {"request": _normalise_request(bedrock.calls[0]), "outputs": outputs}


@pytest.mark.unit
class TestReuseOffGolden:
    def test_the_golden_file_covers_every_scenario(self):
        golden = h.read_json_file(GOLDEN_PATH)
        assert sorted(golden) == sorted(SCENARIOS)

    @pytest.mark.parametrize("name", sorted(SCENARIOS))
    def test_reuse_off_reproduces_the_previous_output(self, name):
        golden = h.read_json_file(GOLDEN_PATH)[name]
        actual = run_scenario(name)
        assert actual["outputs"] == golden["outputs"]
        assert actual["request"] == golden["request"]

    def test_the_scenarios_exercise_key_reuse_when_it_is_on(self):
        """Positive control: with reuse on, the first scenario's output differs from the golden one (the
        earlier text summary is cleared and the prompt quotes the previous title), so the golden comparison
        above is not passing on a scenario key reuse would leave unchanged."""
        scenario = SCENARIOS["mesh-with-reusable-keys"]
        original = dict(scenario["config"])
        scenario["config"] = dict(original, reuseExistingKeys=True)
        try:
            actual = run_scenario("mesh-with-reusable-keys")
        finally:
            scenario["config"] = original
        golden = h.read_json_file(GOLDEN_PATH)["mesh-with-reusable-keys"]
        assert actual["outputs"]["metadata"] != golden["outputs"]["metadata"]
        assert actual["request"] != golden["request"]
