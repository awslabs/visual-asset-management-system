"""With reuseExistingKeys off, the analysis step's output is the output it produced before key reuse existed.

``golden/reuse_off_outputs.json`` holds, per scenario, the Converse request and the files the analysis step
wrote (the file's metadata and attributes, the asset's metadata when written), recorded from the analysis step
as it was before key reuse, the write target and the model settings were added. Each scenario's envelope
carries what key reuse acts on — earlier genai_* values (one the model no longer produces), person-named keys
the default fieldMapping matches, an empty such key, a digest record, and the retired pipeline's
autoGeneratedKeywords — so a reuse-off run that reused, cleared or quoted any of them would differ.

The timestamp is replaced by a marker and image bytes by their length before the comparison; nothing else is
normalised."""

