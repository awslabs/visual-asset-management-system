"""The build-time checks of the per-image locks (locks/tools) fail on what they are there to catch.

check_installed_set.py runs in the image build after the last install; check_upstream_requirements.py right
after the upstream clone. Both are loaded by path, as the Dockerfile runs them, and exercised on small
fixtures.
"""

import importlib.util
import json
import os
import sys

import pytest

TOOLS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "locks", "tools")


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(TOOLS_DIR, f"{name}.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


installed_set = _load("check_installed_set")
upstream = _load("check_upstream_requirements")
sync = _load("sync_constraints")

MARKER = "platform_machine == 'x86_64' and sys_platform == 'linux'"


def _lock(path, pins):
    lines = ["# This file was autogenerated by uv via the following command:", "#    uv export ..."]
    for name, version in pins:
        lines.append(f"{name}=={version} ; {MARKER} \\")
        lines.append("    --hash=sha256:" + "0" * 64)
    path.write_text("\n".join(lines) + "\n")


def _image(tmp_path, build, main, gpl=(), out=()):
    _lock(tmp_path / "requirements-build.lock", build)
    _lock(tmp_path / "requirements.lock", main)
    _lock(tmp_path / "requirements-gpl.lock", gpl)
    (tmp_path / "out-of-lock.json").write_text(
        json.dumps({"packages": [{"name": n, "version": v} for n, v in out]})
    )
    return tmp_path


def _run(monkeypatch, capsys, tmp_path, have, gpl="true"):
    monkeypatch.setattr(installed_set, "installed", lambda: {installed_set.canonical(n): (n, v) for n, v in have})
    monkeypatch.setattr(sys, "argv", ["check_installed_set.py", "--dir", str(tmp_path), "--gpl", gpl])
    code = installed_set.main()
    return code, capsys.readouterr().err


def test_exact_set_passes(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5"), ("Typing_Extensions", "4.16.0")], [("pymeshfix", "0.18.1")],
           [("torchmcubes", "0.1.0")])
    have = [("pip", "26.3"), ("numpy", "2.5.5"), ("typing-extensions", "4.16.0"), ("pymeshfix", "0.18.1"),
            ("torchmcubes", "0.1.0")]
    assert _run(monkeypatch, capsys, tmp_path, have)[0] == 0


def test_extra_package_fails(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5")])
    code, err = _run(monkeypatch, capsys, tmp_path, [("pip", "26.3"), ("numpy", "2.5.5"), ("requests", "2.33.0")])
    assert code == 1 and "not in the lock: requests 2.33.0" in err


def test_missing_and_different_version_fail(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5"), ("scipy", "1.18.1")])
    code, err = _run(monkeypatch, capsys, tmp_path, [("pip", "26.3"), ("numpy", "1.26.4")])
    assert code == 1
    assert "different version: numpy is 1.26.4, the lock has 2.5.5" in err
    assert "missing: scipy 1.18.1" in err


def test_gpl_lock_is_read_only_when_requested(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5")], [("pymeshfix", "0.18.1")])
    base = [("pip", "26.3"), ("numpy", "2.5.5")]
    assert _run(monkeypatch, capsys, tmp_path, base, gpl="false")[0] == 0
    code, err = _run(monkeypatch, capsys, tmp_path, base, gpl="true")
    assert code == 1 and "missing: pymeshfix 0.18.1" in err
    code, err = _run(monkeypatch, capsys, tmp_path, base + [("pymeshfix", "0.18.1")], gpl="false")
    assert code == 1 and "not in the lock: pymeshfix 0.18.1" in err


def test_recorded_out_of_lock_package_must_be_present(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5")], out=[("torchmcubes", "0.1.0")])
    code, err = _run(monkeypatch, capsys, tmp_path, [("pip", "26.3"), ("numpy", "2.5.5")])
    assert code == 1 and "missing: torchmcubes 0.1.0" in err


def test_package_in_lock_and_out_of_lock_is_refused(tmp_path, monkeypatch, capsys):
    _image(tmp_path, [("pip", "26.3")], [("numpy", "2.5.5")], out=[("numpy", "2.5.5")])
    monkeypatch.setattr(installed_set, "installed", lambda: {})
    monkeypatch.setattr(sys, "argv", ["check_installed_set.py", "--dir", str(tmp_path)])
    with pytest.raises(SystemExit, match="both in the lock and in out-of-lock.json"):
        installed_set.main()


def test_two_locks_pinning_one_package_differently_is_refused(tmp_path, monkeypatch):
    _image(tmp_path, [("setuptools", "84.2.1")], [("setuptools", "78.1.0")])
    monkeypatch.setattr(installed_set, "installed", lambda: {})
    monkeypatch.setattr(sys, "argv", ["check_installed_set.py", "--dir", str(tmp_path)])
    with pytest.raises(SystemExit, match="another lock of this image pins"):
        installed_set.main()


def test_lock_line_that_is_not_a_pin_is_refused(tmp_path):
    (tmp_path / "requirements.lock").write_text("requests>=2 ; python_version >= '3'\n")
    with pytest.raises(SystemExit, match="not a pinned requirement"):
        installed_set.read_lock(str(tmp_path / "requirements.lock"))


def test_marker_that_does_not_hold_skips_the_pin(tmp_path):
    (tmp_path / "requirements.lock").write_text("pywin32==300 ; sys_platform == 'win32' \\\n    --hash=sha256:" + "0" * 64 + "\n")
    assert installed_set.read_lock(str(tmp_path / "requirements.lock")) == {}


def _upstream(tmp_path, recorded, cloned):
    (tmp_path / "recorded").mkdir()
    (tmp_path / "clone").mkdir()
    (tmp_path / "recorded" / "requirements.txt.recorded").write_bytes(recorded)
    (tmp_path / "clone" / "requirements.txt").write_bytes(cloned)
    return ["check_upstream_requirements.py", "--recorded", str(tmp_path / "recorded"), "--clone",
            str(tmp_path / "clone"), "requirements.txt"]


def test_upstream_file_equal_passes_even_with_crlf(tmp_path, monkeypatch):
    monkeypatch.setattr(sys, "argv", _upstream(tmp_path, b"numpy==1.26.4\nscipy\n", b"numpy==1.26.4\r\nscipy\r\n"))
    assert upstream.main() == 0


def test_upstream_pin_moved_fails_and_names_the_lines(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(sys, "argv", _upstream(tmp_path, b"numpy==1.26.4\nscipy\n", b"numpy==2.0.0\nscipy\n"))
    assert upstream.main() == 1
    err = capsys.readouterr().err
    assert "upstream has: numpy==2.0.0" in err and "the copy has: numpy==1.26.4" in err


def test_upstream_file_missing_from_the_clone_fails(tmp_path, monkeypatch):
    argv = _upstream(tmp_path, b"a\n", b"a\n")
    os.remove(tmp_path / "clone" / "requirements.txt")
    monkeypatch.setattr(sys, "argv", argv)
    with pytest.raises(SystemExit, match="cannot read the upstream file"):
        upstream.main()


def test_sync_constraints_rewrites_and_checks(tmp_path, monkeypatch):
    (tmp_path / "frozen-set.txt").write_text("# header\nnumpy==2.5.5\ntorch==2.10.0+cu128\n")
    (tmp_path / "pyproject.toml").write_text(f"[tool.uv]\n{sync.BEGIN}\nconstraint-dependencies = []\n{sync.END}\n")
    monkeypatch.setattr(sys, "argv", ["sync_constraints.py", str(tmp_path), "--check"])
    assert sync.main() == 1
    monkeypatch.setattr(sys, "argv", ["sync_constraints.py", str(tmp_path)])
    assert sync.main() == 0
    assert '"torch==2.10.0+cu128",' in (tmp_path / "pyproject.toml").read_text()
    monkeypatch.setattr(sys, "argv", ["sync_constraints.py", str(tmp_path), "--check"])
    assert sync.main() == 0


def test_sync_constraints_refuses_a_source_build_line(tmp_path):
    (tmp_path / "frozen-set.txt").write_text("torchmcubes @ file:///opt/torchmcubes\n")
    with pytest.raises(SystemExit, match="not a `name==version` line"):
        sync.read_frozen(str(tmp_path / "frozen-set.txt"))
